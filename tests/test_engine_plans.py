class AssessmentAccessTests(unittest.TestCase):
    """Record fictional grants only; no namespace, native tool or host access."""
    def descriptor(self, target="whole_device"):
        return {"schema": "patchcairn.assessment.access", "schema_version": 1, "target": target,
                "operations": ["metadata", "diagnosis"], "local_content": [],
                "llm_content": [], "sensitive_exceptions": []}

    def selection(self, identifier="app-range", source="/fictional/app.log"):
        return {"id": identifier, "kind": "path", "source": source,
                "selection": "Fictional nonsecret error codes in one reviewed time range; at most 1024 bytes"}

    def test_legacy_scope_bytes_and_copy_are_preserved(self):
        scope = {"roots": ["fictional selected folder"], "purpose": "Fictional assessment"}
        validated = engine_plans._scope(scope)
        self.assertEqual(encoded(validated), encoded(scope))
        self.assertEqual(digest(validated), digest(scope))
        self.assertIsNot(validated, scope)
        self.assertNotIn("assessment", validated)

    def test_explicit_access_distinguishes_local_sensitive_and_disclosure(self):
        for target in ("whole_device", "selected_paths", "specific_problem"):
            access = self.descriptor(target)
            access.update(operations=["diagnosis", "content_read"], local_content=[self.selection()],
                          sensitive_exceptions=["app-range"])
            scope = {"roots": [], "purpose": "Fictional selected problem", "assessment": access}
            validated = engine_plans._scope(scope)
            self.assertEqual(validated, scope)
            self.assertEqual(validated["assessment"]["llm_content"], [])
            access["llm_content"] = ["app-range"]
            self.assertNotEqual(digest(engine_plans._scope(scope)), digest(validated))
            self.assertEqual(validated["assessment"]["llm_content"], [])

    def test_literal_selector_ids_do_not_infer_neighboring_disclosure(self):
        access = self.descriptor("specific_problem")
        selections = [self.selection("windows-range", "C:/Fictional/App.log"),
                      self.selection("network-range", "//fictional-server/share/app.log"),
                      {"id": "event-fields", "kind": "observation", "source": "windows.system_event_metadata",
                       "selection": "Only fictional selected event IDs; no message bodies"}]
        other_range = self.selection("other-range", "C:/Fictional/App.log")
        other_range["selection"] = "A different fictional time range; at most 512 bytes"
        access.update(operations=["diagnosis", "content_read"], local_content=selections + [other_range],
                      sensitive_exceptions=["windows-range"], llm_content=["event-fields"])
        validated = engine_plans._scope({"roots": [], "purpose": "Fictional ranges", "assessment": access})
        self.assertEqual(validated["assessment"]["llm_content"], ["event-fields"])
        self.assertNotIn("windows-range", validated["assessment"]["llm_content"])
        self.assertNotIn("other-range", validated["assessment"]["llm_content"])

    def test_unknown_mutating_ambiguous_or_unbound_permissions_refuse(self):
        bad = []
        value = self.descriptor(); value["operations"] = ["repair"]; bad.append(value)
        value = self.descriptor(); value["operations"] = ["metadata", "metadata"]; bad.append(value)
        value = self.descriptor(); value["llm_content"] = ["unread-source"]; bad.append(value)
        value = self.descriptor(); value["sensitive_exceptions"] = ["unread-source"]; bad.append(value)
        value = self.descriptor(); value["approved"] = True; bad.append(value)
        value = self.descriptor(); value["local_content"] = [self.selection()]; bad.append(value)
        for source in ("relative/file", "/fictional/../private", "/fictional//app.log", "/fictional/*.log", "c:/fictional/app.log", "C:\\fictional\\app.log", 'C:/fictional/a<b', 'C:/fictional/a>b', 'C:/fictional/a"b', 'C:/fictional/a|b', 'C:/fictional/CONIN$', 'C:/fictional/CONOUT$', 'C:/fictional/COM\u00b9', 'C:/fictional/LPT\u00b3.log'):
            value = self.descriptor(); value.update(operations=["content_read"], local_content=[self.selection(source=source)]); bad.append(value)
        value = self.descriptor(); value.update(operations=["content_read"], local_content=[self.selection(), self.selection()]); bad.append(value)
        value = self.descriptor(); value.update(operations=["content_read"], local_content=[self.selection(source="C:/Fictional/App.log"), self.selection("other-id", "C:/fictional/app.log")]); bad.append(value)
        value = self.descriptor(); value.update(operations=["content_read"], local_content=[self.selection()], llm_content=["app-range", "app-range"]); bad.append(value)
        for number, value in enumerate(bad):
            with self.subTest(case=number), self.assertRaises(WorkflowRefusal):
                engine_plans._scope({"roots": [], "purpose": "Fictional invalid grant", "assessment": value})

    def test_empty_device_or_problem_scope_needs_typed_current_owner_authority(self):
        for target in (None, "selected_paths", "whole_device", "specific_problem"):
            scope = {"roots": [], "purpose": "Fictional assessment"}
            if target is not None:
                scope["assessment"] = self.descriptor(target)
            state = {"owner_id": "owner", "status": "active", "settings_revision": 0,
                     "job": "diagnosis_repair", "stage": "scope", "pending": {},
                     "settings": {"scope": engine_plans._scope(scope), "timing": "now"}, "scope_authorization": None}
            engine = object.__new__(WorkflowEngine)
            engine._change = lambda session, event, mutate, revision: mutate(state)
            engine.evidence_rows = lambda state, ids, **unused: [{"kind": "scope_confirmation", "facts": {"scope_confirmed": True}}]
            self.assertEqual(engine_plans._scope_selected(state["settings"]["scope"]), target in ("whole_device", "specific_problem"))
            if target in ("whole_device", "specific_problem"):
                engine.authorize_scope("fictional", owner_quote="Authorize only the described fictional read-only assessment", owner_message_id="fictional-access")
                self.assertEqual(state["scope_authorization"]["scope_sha256"], digest(scope))
                engine.advance_stage("fictional", evidence_ids=["fictional-scope"])
                self.assertEqual(state["stage"], "symptom")
            else:
                with self.assertRaises(WorkflowRefusal):
                    engine.authorize_scope("fictional", owner_quote="Fictional decision", owner_message_id="fictional-access")
                self.assertIsNone(state["scope_authorization"])


