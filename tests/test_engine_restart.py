def instant(text):
    return datetime.fromisoformat(text.replace("Z", "+00:00"))


def stamp(value):
    return value.strftime("%Y-%m-%dT%H:%M:%S.%fZ")


class RestartStateTests(unittest.TestCase):
    """restart_state, the one reading of a restart marker."""

    def test_each_marker_has_one_reading(self):
        required, gone = {"signal": "required", "source": "exit_code"}, {"signal": "none", "source": "apt.needrestart"}
        seen = {"boot_observed": True, "evidence_id": "fictional-boot", "sha256": "a" * 64, "recorded_utc": "2026-01-02T03:04:05Z"}
        for label, operation, expected in (("no marker", {}, "none"), ("empty marker", {"restart_pending": {}}, "none"),
                                           ("signal", {"restart_pending": required}, "waiting"),
                                           ("gone when read again", {"restart_pending": gone}, "none"),
                                           ("boot", {"restart_pending": required, "restart_verification": seen}, "boot_observed"),
                                           ("gone, then the boot", {"restart_pending": gone, "restart_verification": seen}, "boot_observed"),
                                           ("no boot in the record", {"restart_pending": required, "restart_verification": dict(seen, boot_observed=False)},
                                            "waiting"),
                                           ("empty record", {"restart_pending": required, "restart_verification": None}, "waiting"),
                                           ("a boot without a signal", {"restart_verification": seen}, "none")):
            with self.subTest(label):
                self.assertEqual(engine_journal.restart_state(operation), expected)
        for signal in package_routes.RESTART_SIGNALS:
            with self.subTest(signal=signal):
                self.assertEqual(engine_journal.restart_state({"restart_pending": {"signal": signal, "source": "fictional-probe"}}),
                                 "none" if signal == "none" else "waiting")

    def test_the_service_reads_it_from_the_facade(self):
        self.assertIs(getattr(workflow_core, "restart_state", None), engine_journal.restart_state)


class RestartTests(PackagePlanHelpers, WorkflowFixture):
    """A route's restart signal keeps its step open in the restart class; a signal read again from the same place, or an
    observed later boot, releases it, and the step's result is then recorded once."""

    def signal_call(self, operation_id, signal="required", source="exit_code", **facts):
        """record_restart_pending of the restart signal ``signal`` that the route read from ``source`` for ``operation_id``."""
        operation = self.state()["operations"][operation_id]
        row = self.evidence("outcome", {key: operation[key] for key in ("operation_id", "action_id", "plan_sha256")}
                            | {"outcome": "unknown", "restart_signal": signal, "restart_source": source, **facts})
        return self.engine.record_restart_pending(self.sid, operation_id=operation_id, evidence_id=row)

    def signal(self, *args, **kwargs):
        return self.allowed(self.signal_call, *args, **kwargs)

    def bound(self, operation_id, **facts):
        """The facts that bind a row to the step ``operation_id``, its action and its plan."""
        operation = self.state()["operations"][operation_id]
        return {key: operation[key] for key in ("operation_id", "action_id", "plan_sha256")} | {"outcome": "unknown", **facts}

    def boot(self, operation_id, *, later=True, boot_id="fictional-boot-2", last=None, kind="outcome", facts=None, **changes):
        """A fictional boot reading, observed now and bound to the step: the computer last started at ``last``, by default
        after ``operation_id`` began (or before it); ``changes`` replace record fields, ``kind`` and ``facts`` the row's."""
        started, observed = self.state()["operations"][operation_id]["started_utc"], pc_records.utc_now()
        last = last or (observed if later else stamp(instant(started) - timedelta(days=1)))
        record = {"schema": "patchcairn.boot.observation", "schema_version": 1, "last_boot_utc": last, "boot_id": boot_id, "observed_utc": observed,
                  "source": "fictional.boot_probe", **changes}
        evidence_id = "fictional-boot-" + uuid.uuid4().hex[:12]
        self.engine.register_evidence(self.sid, evidence_id=evidence_id, content=encoded(record), kind=kind, scope=self.scope,
                                      facts=self.bound(operation_id) if facts is None else facts, observed_utc=observed)
        return evidence_id

    def boot_call(self, operation_id, **kwargs):
        return self.engine.record_boot_observation(self.sid, operation_id=operation_id, evidence_id=self.boot(operation_id, **kwargs))

    def booted(self, operation_id, **kwargs):
        return self.allowed(self.boot_call, operation_id, **kwargs)

    def test_verify_after_restart_keeps_outcome_open_until_reprobe(self):
        payload = copy.deepcopy(VARIANTS["firmware_fwupd_device"]["payload"])
        self.assertIn("verify_after_restart", payload["flags"])
        self.package_plan([self.package_action("fictional-firmware", payload, adapter_id="system.firmware_update", kind="firmware_update")], typed=True)
        operation_id = self.start("fictional-firmware")
        updated = {"result": "updated", "verified_postcondition": True}
        # Success needs the check after a restart, with or without a recorded signal.
        self.not_closed(operation_id, "succeeded", "restart-pending", **updated)
        self.signal(operation_id, "required", "linux.reboot_required", boot_id="fictional-boot-1")
        self.assertEqual(self.outstanding(), [(None, True)])
        self.not_closed(operation_id, "succeeded", "restart-pending", **updated)
        self.not_closed(operation_id, "failed", "restart-pending", **DID_NOT_UPDATE)
        # The signal is gone when read again from the same place, yet a firmware update still waits for the boot.
        self.signal(operation_id, "none", "linux.reboot_required")
        self.not_closed(operation_id, "succeeded", "restart-pending", **updated)
        self.refused("no-later-boot", self.boot_call, operation_id, later=False)
        self.refused("no-later-boot", self.boot_call, operation_id, boot_id="fictional-boot-1")  # the boot the step ran in
        self.booted(operation_id)
        self.assertIsNone(self.state()["operations"][operation_id]["outcome"])
        self.close(operation_id, "succeeded", **updated)
        self.assertEqual((self.state()["operations"][operation_id]["outcome"], self.outstanding()), ("succeeded", []))

    def test_post_boot_result_is_terminal_and_resolvable(self):
        payload = self.package_payload("fictional-kernel", variant="terminal_apt_kernel_through_sudo")
        self.package_plan([self.package_action("fictional-kernel", payload)])
        operation_id = self.start("fictional-kernel")
        self.signal(operation_id, "required", "exit_code")
        self.booted(operation_id)
        check = {"result": "could_not_check", "verified_postcondition": False}
        # A failure after the boot carries the facts resolve reads, and closes once.
        self.not_closed(operation_id, "failed", "resolve-facts", **check)
        self.close(operation_id, "failed", **check, **RESOLVE_FACTS)
        state = self.state()
        self.assertEqual((state["operations"][operation_id]["outcome"], state["operations"][operation_id]["resolution"], state["status"]),
                         ("failed", None, "held"))
        self.not_closed(operation_id, "succeeded", "workflow-refusal", result="updated", verified_postcondition=True)
        self.refused("workflow-refusal", self.signal_call, operation_id, "required", "exit_code")
        self.refused("workflow-refusal", self.boot_call, operation_id, boot_id="fictional-boot-3")
        self.assertEqual(self.state()["operations"][operation_id], state["operations"][operation_id])
        # resolve accounts for it with the same facts.
        row = self.evidence("reconciliation", {"operation_id": operation_id, "action_id": "fictional-kernel", "plan_sha256": self.plan_hash,
                                               "outcome": "failed", **RESOLVE_FACTS})
        self.allowed(self.engine.resolve, self.sid, pending_id="reconcile-" + operation_id, evidence_ids=[row], choice="revise_plan",
                     owner_quote="Account for this fictional failed update and plan again.", owner_message_id="fictional-replan-" + uuid.uuid4().hex)
        self.assertEqual(self.state()["operations"][operation_id]["resolution"]["kind"], "replan_required")
        self.assertEqual(self.outstanding(), [])

