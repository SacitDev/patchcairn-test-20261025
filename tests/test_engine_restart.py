    def test_restart_state_follows_the_real_transitions(self):
        self.batch([], [])
        first = self.start("fictional-a1")
        read = lambda operation_id: engine_journal.restart_state(self.state()["operations"][operation_id])
        self.assertEqual(read(first), "none")
        self.signal(first, "recommended", "apt.needrestart")
        self.assertEqual(read(first), "waiting")
        self.signal(first, "none", "apt.needrestart")  # gone when read again: the same reading as no signal
        self.assertEqual(read(first), "none")
        self.close(first, "succeeded", **UPDATED)
        second = self.start("fictional-a2")
        self.signal(second, "required", "exit_code")
        self.assertEqual(read(second), "waiting")
        self.booted(second)
        self.assertEqual(read(second), "boot_observed")
        # The boot and the finished check are separate facts: the outcome says whether the check has finished.
        self.assertIsNone(self.state()["operations"][second]["outcome"])
        self.close(second, "succeeded", **UPDATED)
        self.assertEqual((read(second), self.state()["operations"][second]["outcome"]), ("boot_observed", "succeeded"))

    def test_restart_records_keep_their_layouts(self):
        self.assertEqual(engine_journal.RECORD_FIELDS["patchcairn.boot.observation"], ({"boot_id", "last_boot_utc", "observed_utc", "source"}, set()))
        boot = {"schema": "patchcairn.boot.observation", "schema_version": 1, "last_boot_utc": "2026-01-02T03:04:05Z", "boot_id": None,
                "observed_utc": "2026-01-02T03:04:06Z", "source": "fictional.boot_probe"}
        self.assertIs(engine_journal.typed_record(boot, "patchcairn.boot.observation"), boot)
        for change in ({"mode": "fixture"}, {"boot_id": None, "platform": "windows"}):
            with self.subTest(change=change), self.assertRaises(WorkflowRefusal):
                engine_journal.typed_record(dict(boot, **change), "patchcairn.boot.observation")
        self.batch([])
        operation_id = self.start("fictional-a1")
        self.refused("workflow-refusal", self.boot_call, operation_id)  # no restart is waiting
        self.refused("workflow-refusal", self.signal_call, operation_id, "none", "linux.reboot_required")
        self.refused("invalid-identifier", self.signal_call, operation_id, "required", "../exit")
        for boot_id in ("../boot", 7):  # a boot id that cannot be compared binds nothing
            with self.subTest(boot_id=boot_id):
                self.refused("invalid-identifier", self.signal_call, operation_id, "required", "exit_code", boot_id=boot_id)
        self.refused("workflow-refusal", self.signal_call, operation_id, "maybe", "exit_code")
        self.signal(operation_id, "required", "linux.reboot_required")
        self.signal(operation_id, "required", "linux.reboot_required")  # the same reading again changes nothing
        self.assertEqual(sorted(self.state()["operations"][operation_id]["restart_pending"]), ["signal", "source"])


