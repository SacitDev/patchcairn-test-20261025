    def reading(self, operation_id, signal, offset, source="linux.reboot_required"):
        """An outcome row of a reading of the signal taken ``offset`` microseconds after the step began, both fresh; registering
        a row and submitting it are separate, so a test can submit them in any order."""
        taken = stamp(instant(self.state()["operations"][operation_id]["started_utc"]) + timedelta(microseconds=offset))
        return self.evidence("outcome", self.bound(operation_id, restart_signal=signal, restart_source=source), observed_utc=taken)

    def submit(self, operation_id, row):
        return self.engine.record_restart_pending(self.sid, operation_id=operation_id, evidence_id=row)

    def test_an_older_clearing_reading_never_replaces_a_newer_requirement(self):
        # Two fresh readings from one place, submitted newest first: the older "none" must not release the wait.
        self.batch([])
        operation_id = self.start("fictional-a1")
        clear, required = self.reading(operation_id, "none", 1), self.reading(operation_id, "required", 2)
        self.allowed(self.submit, operation_id, required)
        self.refused("restart-signal-kept", self.submit, operation_id, clear)
        operation = self.state()["operations"][operation_id]
        self.assertEqual(operation["restart_pending"], {"signal": "required", "source": "linux.reboot_required"})
        self.assertEqual(engine_journal.restart_state(operation), "waiting")
        self.assertEqual(self.outstanding(), [(None, True)])
        # The newest reading submitted again changes nothing, and a reading taken after it still clears the signal.
        self.allowed(self.submit, operation_id, required)
        self.signal(operation_id, "none", "linux.reboot_required")
        self.assertEqual(engine_journal.restart_state(self.state()["operations"][operation_id]), "none")

    def test_an_older_requirement_never_replaces_a_newer_clearing_reading(self):
        self.batch([])
        operation_id = self.start("fictional-a1")
        first, gone = self.reading(operation_id, "required", 1), self.reading(operation_id, "none", 3)
