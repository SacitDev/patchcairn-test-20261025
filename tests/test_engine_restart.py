    def test_exit_code_signal_released_only_by_a_later_boot(self):
        self.batch([], [])
        operation_id = self.start("fictional-a1")
        self.signal(operation_id, "required", "exit_code", boot_id="fictional-boot-1")
        operation = self.state()["operations"][operation_id]
        self.assertEqual(encoded(operation["restart_pending"]), b'{"signal":"required","source":"exit_code"}')
        self.assertEqual(self.outstanding(), [(None, True)])
        # An exit code cannot be read again: no later reading, from it or from another place, releases or replaces it.
        for signal, source in (("none", "exit_code"), ("none", "linux.reboot_required"), ("recommended", "apt.needrestart")):
            with self.subTest(signal=signal, source=source):
                self.refused("restart-signal-kept", self.signal_call, operation_id, signal, source)
        self.assertEqual(self.state()["operations"][operation_id]["restart_pending"], {"signal": "required", "source": "exit_code"})
        self.not_closed(operation_id, "succeeded", "restart-pending", result="updated")
        self.refused("no-later-boot", self.boot_call, operation_id, later=False)
        self.refused("no-later-boot", self.boot_call, operation_id, boot_id="fictional-boot-1")
        boot = self.boot(operation_id)
        self.allowed(self.engine.record_boot_observation, self.sid, operation_id=operation_id, evidence_id=boot)
        verification = self.state()["operations"][operation_id]["restart_verification"]
        self.assertEqual(verification, {"boot_observed": True, "evidence_id": boot, "sha256": self.state()["evidence"][boot]["sha256"],
                                        "recorded_utc": verification["recorded_utc"]})
        self.assertEqual(self.outstanding(), [(None, False)])  # released; the step is in flight until its result
        self.refused("workflow-refusal", self.signal_call, operation_id, "required", "exit_code")
        self.close(operation_id, "succeeded", **UPDATED)
        # A signal that can be read again ends when the same place no longer reports it, without a boot.
        second = self.start("fictional-a2")
        self.signal(second, "recommended", "apt.needrestart")
        self.not_closed(second, "succeeded", "restart-pending", result="updated")
        self.signal(second, "none", "apt.needrestart")
        self.assertEqual(self.outstanding(), [(None, False)])
        self.close(second, "succeeded", **UPDATED)
        self.assertEqual(self.outstanding(), [])

    def between(self, operation_id):
        """A time after ``operation_id`` began and before anything recorded since."""
        return stamp(instant(self.state()["operations"][operation_id]["started_utc"]) + timedelta(microseconds=1))

    def test_a_known_boot_is_refused_whatever_time_it_claims(self):
        self.batch([])
        operation_id = self.start("fictional-a1")
        self.signal(operation_id, "required", "exit_code", boot_id="fictional-boot-1")
        between = self.between(operation_id)
        # The id the signal was read in, claimed as a start after the step began but before that reading, and after it.
        self.refused("no-later-boot", self.boot_call, operation_id, boot_id="fictional-boot-1", last=between)
        self.refused("no-later-boot", self.boot_call, operation_id, boot_id="fictional-boot-1")
        # A new id that claims to have started before a reading taken in the old boot contradicts that reading.
        self.refused("no-later-boot", self.boot_call, operation_id, boot_id="fictional-boot-2", last=between)
        # A reading with no id cannot show that the id the step ran in changed.
        self.refused("boot-inconsistent", self.boot_call, operation_id, boot_id=None)
        self.assertNotIn("restart_verification", self.state()["operations"][operation_id])
        self.assertEqual(self.outstanding(), [(None, True)])
        self.booted(operation_id)

