FIXTURES = ROOT / "tests" / "fixtures"
PACKAGE_COMMON = {"schema", "schema_version", "manager", "operation", "id", "version", "source", "group", "flags", "preflight",
                  "transaction_sha256", "run_kind"}
PACKAGE_RUN = {"dependencies", "agreements", "recipe", "run_files", "executable", "environment_sha256"}
PACKAGE_OPTIONAL = {"depends_on", "update", "device", "conditional", "settings_page"}
CONDITIONAL_FLAGS = {"install_scripts": "run_install_scripts", "runtime_line_change": "runtime_line_change"}


def payload_problem(adapter_id, payload):
    """The refusal code of the first rule of the patchcairn.package payload contract that ``payload`` breaks, or None. The
    frozen fixtures follow this reading of the contract; the engine's binding gives the same codes for them."""
    facts = pc_records.ADAPTERS[adapter_id]
    if set(payload) - PACKAGE_COMMON - PACKAGE_RUN - PACKAGE_OPTIONAL or PACKAGE_COMMON - set(payload):
        return "package-payload-unknown-key"
    if payload["run_kind"] not in facts["run_kinds"]:
        return "package-payload-run-kind"
    if payload["run_kind"] == "settings" and (PACKAGE_RUN & set(payload) or "settings_page" not in payload):
        return "package-payload-settings"
    if payload["run_kind"] != "settings" and ("settings_page" in payload or PACKAGE_RUN - set(payload)):
        return "package-payload-settings-page"
    firmware = adapter_id == pc_records.ADAPTER_SYSTEM_FIRMWARE_UPDATE
    if ("device" in payload) != firmware or firmware and not isinstance(payload["device"], dict):
        return "package-payload-device"
    if not set(payload["flags"]) <= pc_records.ROUTE_FLAGS:
        return "package-payload-flags"
    if firmware and not {"firmware", "high_risk"} <= set(payload["flags"]):
        return "package-payload-firmware-flags"
    expected = {CONDITIONAL_FLAGS[flag] for flag in payload["flags"] if flag in CONDITIONAL_FLAGS}
    if ("conditional" in payload) != bool(expected) or set(payload.get("conditional", {})) != expected:
        return "package-payload-conditional"
    return None


class PayloadFixtureTests(unittest.TestCase):
    """The frozen package payload fixtures: canonical bytes, one variant per run kind, one case per invalid combination."""

    def load(self, name):
        return json.loads((FIXTURES / name).read_text(encoding="ascii"))

    def test_valid_payload_variants_follow_the_contract(self):
        variants = self.load("package-payload.json")["variants"]
        self.assertEqual([row["name"] for row in variants], ["process_winget_upgrade", "terminal_apt_kernel_through_sudo",
                                                             "settings_windows_driver_handoff", "firmware_fwupd_device"])
        self.assertEqual({row["payload"]["run_kind"] for row in variants}, set(pc_records.RUN_KINDS))
        for row in variants:
            payload = row["payload"]
            with self.subTest(variant=row["name"]):
                self.assertEqual(row["encoded"], encoded(payload).decode("ascii"))
                self.assertEqual(row["sha256"], digest(payload))
                self.assertEqual(payload["transaction_sha256"], digest(payload["preflight"]))
                self.assertEqual((payload["schema"], payload["schema_version"]), ("patchcairn.package", 1))
                self.assertIn(payload["schema"], pc_records.PLANNED_SCHEMAS)
                self.assertIsNone(payload_problem(row["adapter_id"], payload))
                self.assertNotRegex(row["encoded"], r"(?i)\\\\users\\\\|/home/|/users/")
        firmware = [row for row in variants if row["adapter_id"] == pc_records.ADAPTER_SYSTEM_FIRMWARE_UPDATE]
        self.assertEqual([row["payload"]["device"]["number"] for row in firmware], [1])

    def test_each_invalid_payload_breaks_exactly_its_rule(self):
        cases = self.load("package-payload-invalid.json")["cases"]
        self.assertEqual({row["rule"] for row in cases}, {
            "settings with recipe", "settings with executable", "settings with run_files", "process with settings_page",
            "terminal with settings_page", "device on any other adapter", "firmware without exactly one device",
            "a run_kind outside the adapter's", "flags outside ROUTE_FLAGS", "firmware without the firmware and high_risk flags",
            "conditional not matching the flags", "unknown keys"})
        self.assertEqual({row["code"] for row in cases}, {
            "package-payload-settings", "package-payload-settings-page", "package-payload-device", "package-payload-run-kind",
            "package-payload-flags", "package-payload-firmware-flags", "package-payload-conditional", "package-payload-unknown-key"})
        self.assertEqual(len({row["name"] for row in cases}), len(cases))
        for row in cases:
            with self.subTest(case=row["name"]):
                self.assertEqual(payload_problem(row["adapter_id"], row["payload"]), row["code"])


class WorkflowTests(WorkflowFixture):
    def test_protected_os_consent_cannot_be_bypassed_by_approval_or_evidence_alone(self):
        # Storage adapters never involve an OS prompt (pc_records facts). This fixture stands in for a per-route
        # adapter (package.upgrade, whose executor is not written yet) so the generic consent gate is exercised.
        facts = dict(pc_records.ADAPTERS)
        facts["storage.backup_create"] = {**facts["storage.backup_create"], "os_consent": "per_route"}
        with mock.patch.object(pc_records, "ADAPTERS", facts):
            self.apply_ready(protected=True)
            self.protected_consent_sequence()

    def protected_consent_sequence(self):
        with self.assertRaises(WorkflowRefusal):
            self.begin()
        consent = self.evidence("protected_consent", {"action_id": "fictional-action", "plan_sha256": self.plan_hash, "actual_os_consent": True})
        with self.assertRaises(WorkflowRefusal):
            self.begin(owner_consent_evidence_id=consent)
        self.engine.record_protected_consent(self.sid, action_id="fictional-action", plan_sha256=self.plan_hash, evidence_id=consent, owner_quote="I handled the fictional protected prompt.", owner_message_id="fictional-consent")
        self.begin(owner_consent_evidence_id=consent)

    def test_external_official_handoff_is_exact_typed_data_and_never_executed(self):
        self.sid = self.engine.create_session(scope=self.scope, checkpoints=[], platform="windows")["session_id"]
        self.plan_ready()
        plan = copy.deepcopy(self.plan)
        action = plan["actions"][0]
        inventory_row = self.state()["evidence"][action["target_inventory_evidence_id"]]
        inventory = json.loads((self.engine.work / self.sid / inventory_row["path"]).read_bytes())
        provenance = self.evidence("research", {"official_sources_checked": True})
        recovery = {"schema": "patchcairn.external.recovery", "schema_version": 1, "strategy": "no_verified_rollback", "evidence_ids": [], "limits": "Fictional handoff fixture; real reversibility has not been established"}
        verification = {"schema": "patchcairn.external.verification", "schema_version": 1, "original_success_condition": "The fictional expected behavior works", "checks": [{"check_id": "fictional-behavior", "description": "Observe fictional behavior", "expected_result": "The expected fictional result"}]}
        external = {"schema": "patchcairn.external.plan", "schema_version": 1, "kind": "update", "platform": "windows", "mode": "fixture", "catalog_id": "windows.msiexec.install", "official_tool": "msiexec.exe", "argv": ["/i", str(self.root / "work" / "fictional-update.msi"), "/passive", "/norestart"], "targets": ["Fictional.Package"], "target_versions": {"Fictional.Package": "2.0"}, "sources": ["https://learn.microsoft.com/windows/win32/msi/windows-installer-portal"], "provenance_evidence_ids": [provenance], "compatibility_evidence_ids": [provenance], "recovery_plan": recovery, "recovery_plan_sha256": digest(recovery), "verification_plan": verification, "verification_plan_sha256": digest(verification), "scope": self.scope}
        external["target_identities"] = {"Fictional.Package": {"channel": "stable", "architecture": "x64", "publisher": "Fictional Publisher", "content_sha256": digest(b"fictional official content"), "source_id": "fictional-official", "installation_scope": "user"}}
        payload = {"schema": "patchcairn.external.adapter", "schema_version": 1, "operation": "system.reviewed_external", "external_plan": external, "external_plan_sha256": digest(external), "inventory_sha256": digest(inventory)}
        action.update(kind="update", adapter_id=payload["operation"], adapter_payload_evidence_id=self.raw_evidence("adapter_payload", payload), adapter_payload_sha256=digest(payload), adapter_plan_sha256=digest(external), requires_os_consent=True)
        self.plan = plan
        self.plan_hash = self.engine.register_plan(self.sid, plan=plan)["data"]["plan_sha256"]
        without_consent = copy.deepcopy(plan)
        without_consent["actions"][0]["requires_os_consent"] = False
        with self.assertRaisesRegex(WorkflowRefusal, "protected-system consent"):
            self.engine.register_plan(self.sid, plan=without_consent)
        for reviewer, role in (("external-review-a", "compatibility_data"), ("external-review-b", "evidence_security")):
            self.engine.record_review(self.sid, plan_sha256=self.plan_hash, reviewer_id=reviewer, role=role, verdict="approved", evidence_ids=[self.evidence("review", {"checked": True})], notes="Fictional exact external handoff review")
        self.engine.approve_plan(self.sid, plan_sha256=self.plan_hash, action_ids=["fictional-action"], owner_quote="Approve only this exact fictional version and variant.", owner_message_id="fictional-external-approval")
        self.engine.advance_stage(self.sid, evidence_ids=[])
        with self.assertRaises(WorkflowRefusal):
            self.begin()  # Generic boolean preconditions cannot replace actual artifact/signature proof.
        self.assertFalse(self.state()["operations"])
        artifact = Path(external["argv"][1])
        artifact.write_bytes(b"fictional official content")
        from scoped_fs import ScopedRoot
        with ScopedRoot(str(artifact.parent), quiet_workspace=True) as pinned:
            artifact_record = pinned.inspect(artifact.name, hash_file=True, max_bytes=64 * 1024 * 1024)
        identity = external["target_identities"]["Fictional.Package"]
        signature = {"schema": "patchcairn.publisher.signature", "schema_version": 1, "mode": "fixture", "platform": "windows", "artifact_sha256": identity["content_sha256"], "publisher": identity["publisher"], "status": "verified", "source_id": identity["source_id"], "method": "windows.authenticode", "observed_utc": utc_now()}
        signature_id = self.raw_evidence("research", signature)
        metadata = {"schema": "patchcairn.installer.metadata", "schema_version": 1, "mode": "fixture", "platform": "windows", "artifact_sha256": identity["content_sha256"], "target_id": "Different.Fictional.Package", "version": "2.0", "channel": identity["channel"], "architecture": identity["architecture"], "installation_scope": identity["installation_scope"], "publisher": identity["publisher"], "source_id": identity["source_id"], "observed_utc": utc_now()}
        def proof_row(metadata_id):
            proof = {"schema": "patchcairn.external.preflight", "schema_version": 1, "action_id": action["action_id"], "plan_sha256": self.plan_hash, "external_plan_sha256": action["adapter_plan_sha256"], "mode": "fixture", "platform": "windows", "observed_utc": utc_now(), "targets": {"Fictional.Package": {**identity, "version": "2.0", "artifact_path": str(artifact), "artifact_record": artifact_record, "signature_evidence_id": signature_id, "metadata_evidence_id": metadata_id}}}
            self.sequence += 1
            proof_id = "fictional-preflight-" + str(self.sequence)
            precondition_id = self.precondition()
            facts = self.state()["evidence"][precondition_id]["facts"]
            self.engine.register_evidence(self.sid, evidence_id=proof_id, kind="precondition", content=encoded(proof), scope=self.scope, facts=facts)
            return self.state()["evidence"][proof_id]
        wrong_metadata = proof_row(self.raw_evidence("research", metadata))
        with self.assertRaisesRegex(WorkflowRefusal, "Actual package metadata"):
            self.engine._external_preflight(self.state(), action, [wrong_metadata])
        metadata["target_id"] = "Fictional.Package"
        matching_metadata = proof_row(self.raw_evidence("research", metadata))
        self.verified.clear()
        self.engine._external_preflight(self.state(), action, [matching_metadata])
        # The artifact bytes are re-read by the service's verifier, never by the engine.
        self.assertEqual(self.verified, [{"kind": "installer_artifact", "path": str(artifact), "record": artifact_record, "sha256": identity["content_sha256"]}])
        self.artifact_refusal = pc_records.Refusal("recovery-changed", "The actual selected official artifact bytes differ")
        with self.assertRaisesRegex(WorkflowRefusal, "artifact bytes differ"):
            self.engine._external_preflight(self.state(), action, [matching_metadata])
        self.artifact_refusal = None
        self.assertFalse(self.state()["operations"])  # Proof validation itself never installs or issues a ticket.
        repair = copy.deepcopy(external)
        repair.update(kind="repair", catalog_id="windows.dism.restorehealth", official_tool="Dism.exe", argv=["/Online", "/Cleanup-Image", "/RestoreHealth"], targets=["windows.component_store"], target_versions={}, target_identities={})
        with self.assertRaisesRegex(WorkflowRefusal, "component-specific"):
            self.engine.validate_external_plan(self.state(), repair, inventory)
        external["argv"].append("--unreviewed-option")
        payload["external_plan_sha256"] = digest(external)
        action.update(adapter_payload_evidence_id=self.raw_evidence("adapter_payload", payload), adapter_payload_sha256=digest(payload), adapter_plan_sha256=digest(external))
        with self.assertRaises(WorkflowRefusal):
            self.engine.register_plan(self.sid, plan=plan)
        self.assertFalse(self.state()["operations"])


