    def test_a_comma_is_a_manager_value_but_never_reaches_an_argv(self):
        # A cask version and its dependencies can hold a comma; the payload reader takes it, and the argv grammar still refuses it.
        upgrade = pc_records.ADAPTER_PACKAGE_UPGRADE
        self.accepted(upgrade, self.payload("process_winget_upgrade", version="1.2,34", dependencies=["example-cask@1.2,34"]))
        for field, value in (("version", "1.2, 34"), ("version", "1.2;34"), ("dependencies", ["example cask@1.2"])):
            with self.subTest(field=field, value=value):
                self.refused("package-payload-field", upgrade, self.payload("process_winget_upgrade", **{field: value}))
        import package_routes
        for slot in ("version", "name", "spec", "nevra", "id"):
            with self.subTest(slot=slot), self.assertRaises(pc_records.Refusal):
                package_routes.variable(slot, "1.2,34")

    def test_handoff_and_firmware_payloads_bound_generically(self):
        handoff, firmware = pc_records.ADAPTER_SYSTEM_UPDATE_HANDOFF, pc_records.ADAPTER_SYSTEM_FIRMWARE_UPDATE
        self.accepted(handoff, self.payload("settings_windows_driver_handoff"))
        self.accepted(firmware, self.payload("firmware_fwupd_device"))
        # A firmware update through Windows Settings binds the same way: the adapter decides, never the manager.
        windows = self.firmware("settings_windows_driver_handoff")
        self.accepted(firmware, windows)
        for manager in ("examplefw", "winupdate", "fwupd"):
            with self.subTest(manager=manager):
                self.accepted(firmware, dict(self.payload("firmware_fwupd_device"), manager=manager))
                self.accepted(firmware, dict(windows, manager=manager))
                self.refused("package-payload-device", handoff, dict(self.payload("settings_windows_driver_handoff", manager=manager),
                                                                     device=windows["device"]))
        self.refused("package-payload-device", firmware, self.payload("firmware_fwupd_device", device=None))
        self.refused("package-payload-firmware-flags", firmware, self.firmware("settings_windows_driver_handoff", flags=["firmware"]))
        self.refused("package-payload-operation", handoff, self.payload("firmware_fwupd_device"))
        self.refused("package-payload-device", firmware, self.firmware("settings_windows_driver_handoff", device={"id": "fictional-device-7", "number": 0,
                                                                                                            "target_version": "1.0.7"}))

    def test_run_kind_must_be_allowed_by_adapter(self):
        templates = {"process": "process_winget_upgrade", "terminal": "terminal_apt_kernel_through_sudo", "settings": "settings_windows_driver_handoff"}
        bound = 0
        for adapter_id, operation in engine_updates.OPERATIONS.items():
            facts = pc_records.ADAPTERS[adapter_id]
            for run_kind, name in templates.items():
                if adapter_id == pc_records.ADAPTER_SYSTEM_FIRMWARE_UPDATE:
                    payload = self.firmware(name)
                else:
                    payload = self.payload(name, operation=operation)
                with self.subTest(adapter_id=adapter_id, run_kind=run_kind):
                    if run_kind in facts["run_kinds"]:
                        self.accepted(adapter_id, payload)
                        bound += 1
                    else:
                        self.refused("package-payload-run-kind", adapter_id, payload)
        self.assertEqual(bound, sum(len(pc_records.ADAPTERS[adapter_id]["run_kinds"]) for adapter_id in engine_updates.OPERATIONS))

    def test_every_update_and_repair_adapter_is_bound(self):
        # engine_plans.action_binding sends exactly these families here, so no adapter of them can arrive without its operation.
        self.assertEqual(set(engine_updates.OPERATIONS), {adapter_id for adapter_id, facts in pc_records.ADAPTERS.items()
                                                          if facts["family"] in ("update", "repair")})

    def test_reviewed_installer_route_and_its_records_are_retired(self):
        # The local-installer route is gone, and the engine knows none of its records, nor the coordinator-attested
        # signature and metadata records it relied on.
        retired = {"patchcairn.external.adapter", "patchcairn.external.plan", "patchcairn.external.preflight", "patchcairn.external.receipt",
                   "patchcairn.external.recovery", "patchcairn.external.verification", "patchcairn.publisher.signature",
                   "patchcairn.installer.metadata", "patchcairn.restart.pending", "patchcairn.restart.verification",
                   "patchcairn.windows.boot.observation"}
        self.assertFalse(retired & pc_records.SCHEMAS)
        self.assertFalse(retired & set(engine_journal.RECORD_FIELDS))
        self.assertFalse(retired & set(pc_records.READERS))
        self.assertLessEqual({"patchcairn.package", "patchcairn.boot.observation"}, set(engine_journal.RECORD_FIELDS))
        for name in ("record_protected_consent", "validate_external_plan", "external_preflight", "_external_preflight", "decide_restart",
                     "validate_restart_verification", "record_restart_verification"):
            self.assertFalse(hasattr(type(self.engine), name), name)
        # A plan cannot name the retired id, and an action stored under it, with its retired record, stays held at the binding.
        with self.assertRaises(pc_records.Refusal) as caught:
            pc_records.adapter_facts("system.reviewed_external", requires_os_consent=True)
        self.assertEqual(caught.exception.code, "unknown-adapter")
        record = {"schema": "patchcairn.external.adapter", "schema_version": 1, "operation": "system.reviewed_external"}
        inventory = {"fictional": "inventory"}
        action = {"adapter_id": "system.reviewed_external", "adapter_plan_sha256": digest(record), "adapter_payload_sha256": digest(record),
                  "adapter_payload_evidence_id": self.raw_evidence("adapter_payload", record), "target_inventory_sha256": digest(inventory),
                  "target_inventory_evidence_id": self.raw_evidence("inventory", inventory)}
        with self.assertRaises(WorkflowRefusal) as caught:
            self.engine.action_binding(self.state(), action)
        self.assertEqual(caught.exception.code, "adapter-held")


