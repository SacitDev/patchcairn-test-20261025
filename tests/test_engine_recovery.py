"""Fictional-only tests of the recovery checks through the injected verifier (engine_recovery).
All generated bytes live under work/wf.

Run with supported Python: -I -S -B -m unittest discover -s tests -p test_engine_recovery.py -v
No test collects host inventory, creates a schedule, executes a plan or cleans a host.
"""
from __future__ import annotations

import copy
import json
from pathlib import Path
import sys
import unittest

sys.dont_write_bytecode = True
ROOT = Path(__file__).absolute().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from workflow_core import WorkflowEngine, WorkflowRefusal, digest
import pc_records
from test_engine_journal import WorkflowFixture


class WorkflowTests(WorkflowFixture):
    def test_boolean_recovery_is_not_a_backup_or_restore_proof(self):
        self.plan_ready()
        plan = copy.deepcopy(self.plan)
        plan["actions"][0]["requires_recovery"] = True
        plan["actions"][0]["recovery_evidence_ids"] = [self.evidence("recovery", {"restore_verified": True, "protected": True})]
        with self.assertRaises(WorkflowRefusal):
            self.engine.register_plan(self.sid, plan=plan)

    def test_required_recovery_hands_exact_receipts_to_the_verifier_and_holds_its_refusal(self):
        self.plan_ready()
        recovery_id = self.verified_recovery()
        binding = self.recovery_binding(recovery_id)
        plan = copy.deepcopy(self.plan)
        plan["actions"][0].update(requires_recovery=True, recovery_evidence_ids=[recovery_id])
        self.verified.clear()
        self.engine.register_plan(self.sid, plan=plan)
        self.assertEqual(self.verified, [{"kind": "backup_recovery", "output_root": binding["output_root"], "backup_receipt": binding["backup_receipt"], "restore_receipt": binding["restore_receipt"], "purge_receipt": None}])
        before = self.state()["revision"]
        self.artifact_refusal = pc_records.Refusal("recovery-changed", "Fictional restored bytes changed on disk")
        with self.assertRaisesRegex(WorkflowRefusal, "Fictional restored bytes changed") as caught:
            self.engine.register_plan(self.sid, plan=plan)
        self.assertEqual(caught.exception.code, "recovery-changed")
        self.assertEqual(self.state()["revision"], before)

    def test_recovery_retention_must_name_every_artifact_before_the_verifier_is_asked(self):
        self.plan_ready()
        binding = self.recovery_binding(self.verified_recovery())
        retention = json.loads((self.engine.work / self.sid / self.state()["evidence"][binding["retention_evidence_id"]]["path"]).read_bytes())
        retention["artifacts"].pop(binding["backup_receipt"]["archive"])
        binding["retention_evidence_id"] = self.raw_evidence("retention", retention)
        plan = copy.deepcopy(self.plan)
        plan["actions"][0].update(requires_recovery=True, recovery_evidence_ids=[self.raw_evidence("recovery", binding)])
        self.verified.clear()
        with self.assertRaisesRegex(WorkflowRefusal, "retention record must protect"):
            self.engine.register_plan(self.sid, plan=plan)
        self.assertEqual(self.verified, [])

    def test_rechecks_hold_without_the_service_verifier_or_with_a_broken_one(self):
        self.plan_ready()
        recovery_id = self.verified_recovery()
        plan = copy.deepcopy(self.plan)
        plan["actions"][0].update(requires_recovery=True, recovery_evidence_ids=[recovery_id])
        before = self.state()["revision"]
        for verifier, code in ((None, "verifier-missing"), (lambda binding: True, "verifier-contract")):
            with self.subTest(code=code), self.assertRaises(WorkflowRefusal) as caught:
                WorkflowEngine(self.root, verify_artifact=verifier).register_plan(self.sid, plan=plan)
            self.assertEqual(caught.exception.code, code)
        self.assertEqual(self.state()["revision"], before)
        self.plan_hash = self.engine.register_plan(self.sid, plan=plan)["data"]["plan_sha256"]
        self.plan = plan
        for reviewer, role in (("verifier-review-a", "compatibility_data"), ("verifier-review-b", "evidence_security")):
            self.engine.record_review(self.sid, plan_sha256=self.plan_hash, reviewer_id=reviewer, role=role, verdict="approved", evidence_ids=[self.evidence("review", {"checked": True})], notes="Fictional exact review")
        self.engine.approve_plan(self.sid, plan_sha256=self.plan_hash, action_ids=["fictional-action"], owner_quote="Apply this exact fictional action.", owner_message_id="fictional-verifier-plan")
        self.engine.advance_stage(self.sid, evidence_ids=[])
        # The begin-time re-check of a dependent action holds when no verifier was supplied.
        bare = WorkflowEngine(self.root)
        with self.assertRaises(WorkflowRefusal) as caught:
            bare.begin_operation(self.sid, action_id="fictional-action", plan_sha256=self.plan_hash, precondition_evidence_ids=[self.precondition(recovery_verified=True)])
        self.assertEqual(caught.exception.code, "verifier-missing")
        self.assertFalse(self.state()["operations"])
        self.verified.clear()
        operation = self.engine.begin_operation(self.sid, action_id="fictional-action", plan_sha256=self.plan_hash, precondition_evidence_ids=[self.precondition(recovery_verified=True)])
        self.assertTrue(operation["data"]["operation_id"])
        self.assertTrue(self.verified)
        self.assertEqual({binding["kind"] for binding in self.verified}, {"backup_recovery"})

    def test_purge_recovery_must_match_original_quarantine_and_cover_its_files(self):
        self.plan_ready()
        recovery_a = self.verified_recovery("fictional-recovery-a", b"Fictional selected file A")
        recovery_b = self.verified_recovery("fictional-recovery-b", b"Fictional selected file B")
        binding_a, binding_b = self.recovery_binding(recovery_a), self.recovery_binding(recovery_b)
        original_b = self.purge_receipt_for(binding_b)

        def candidate(receipt, output_root, recovery_id):
            plan = copy.deepcopy(self.plan)
            action = plan["actions"][0]
            lower = {"schema": "patchcairn.storage", "schema_version": 1, "kind": "purge", "receipt": receipt, "irreversible": True}
            payload = {"schema": "patchcairn.storage.adapter", "schema_version": 1, "operation": "storage.purge", "storage_plan": lower, "storage_plan_sha256": digest(lower), "output_root": output_root, "mode": "fixture", "protected_roots": []}
            action.update(kind="permanent_purge", adapter_id=payload["operation"], adapter_payload_evidence_id=self.raw_evidence("adapter_payload", payload), adapter_payload_sha256=digest(payload), adapter_plan_sha256=digest(lower), target_inventory_evidence_id=self.raw_evidence("inventory", receipt), target_inventory_sha256=digest(receipt), requires_recovery=True, recovery_evidence_ids=[recovery_id])
            return plan

        unbacked_b = copy.deepcopy(original_b)
        unbacked_b.update(recovery_required=False, recovery_backup=None, recovery_verification=None)
        forged_b = copy.deepcopy(original_b)
        forged_b.update(recovery_backup=binding_a["backup_receipt"], recovery_verification=binding_a["restore_receipt"])
        for receipt, output, reason in ((unbacked_b, binding_b["output_root"], "originally unbacked"), (original_b, binding_b["output_root"], "exact original")):
            plan = candidate(receipt, output, recovery_a)
            before = self.state()["revision"]
            with self.subTest(reason=reason), self.assertRaisesRegex(WorkflowRefusal, reason):
                self.engine.register_plan(self.sid, plan=plan)
            self.assertEqual(self.state()["revision"], before)
        # Coverage of the quarantined originals is read from the manifest by the service's verifier
        # (tests/test_service_backup.py); the engine hands it the exact purge receipt and holds its refusal.
        forged = candidate(forged_b, binding_a["output_root"], recovery_a)
        self.verified.clear()
        self.artifact_refusal = pc_records.Refusal("recovery-changed", "Recovery must cover the exact quarantined originals")
        before = self.state()["revision"]
        with self.assertRaisesRegex(WorkflowRefusal, "cover the exact quarantined"):
            self.engine.register_plan(self.sid, plan=forged)
        self.assertEqual(self.verified[-1]["purge_receipt"], forged_b)
        self.assertEqual(self.state()["revision"], before)
        self.artifact_refusal = None

        self.verified.clear()
        correct = candidate(original_b, binding_b["output_root"], recovery_b)
        result = self.engine.register_plan(self.sid, plan=correct)
        self.assertEqual(result["data"]["plan_sha256"], digest(correct))
        self.assertEqual(self.verified, [{"kind": "backup_recovery", "output_root": binding_b["output_root"], "backup_receipt": binding_b["backup_receipt"], "restore_receipt": binding_b["restore_receipt"], "purge_receipt": original_b}])
        self.assertFalse(self.state()["operations"])


if __name__ == "__main__":
    unittest.main()
