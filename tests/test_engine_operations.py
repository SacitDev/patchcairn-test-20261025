class FiredRunTests(PackagePlanHelpers, WorkflowFixture):
    """A fired scheduled run: high_risk payloads and adapters a schedule may not act on are refused at begin."""

    def fired(self, flags):
        patcher = mock.patch.object(pc_records, "utc_now")
        clock = patcher.start()
        self.addCleanup(patcher.stop)
        base = datetime.now(timezone.utc)
        stamp = lambda moment: moment.isoformat().replace("+00:00", "Z")
        clock.return_value = stamp(base)
        self.engine.setup(self.sid, control="automatic", timing="scheduled")
        due = base + timedelta(minutes=1)
        self.engine.configure_schedule(self.sid, schedule={"when_utc": stamp(due), "description": "Fictional schedule"}, owner_quote="At the agreed time.",
                                       owner_message_id="fictional-schedule-" + uuid.uuid4().hex)
        clock.return_value = stamp(due + timedelta(seconds=1))
        self.schedule_trigger("fictional-trigger")
        self.package_plan([self.package_action("fictional-a1", self.package_payload("fictional-a1", flags=flags))])

    def test_a_high_risk_payload_never_starts_in_a_fired_run(self):
        self.fired(["high_risk"])
        self.not_started("fictional-a1", "fired-run-refused")

    def test_a_policy_on_an_adapter_a_schedule_may_not_use_never_starts(self):
        action = {"adapter_id": pc_records.ADAPTER_PACKAGE_UPGRADE}
        self.assertFalse(pc_records.ADAPTERS[action["adapter_id"]]["scheduled_policy_coverable"])
        self.assertTrue(engine_operations._fired_run_refused(action, {"flags": []}, {"kind": "standing_policy"}))
        self.assertFalse(engine_operations._fired_run_refused({"adapter_id": pc_records.ADAPTER_STORAGE_BACKUP_CREATE}, {}, {"kind": "standing_policy"}))
        self.assertFalse(engine_operations._fired_run_refused(action, {"flags": []}, {"kind": "exact_plan"}))
        self.assertTrue(engine_operations._fired_run_refused(action, {"flags": ["high_risk"]}, {"kind": "exact_plan"}))


