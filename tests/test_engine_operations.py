class WorkflowTests(WorkflowFixture):
    def test_begin_requires_current_fresh_meaningful_preconditions(self):
        self.apply_ready()
        for overrides in ({"content_matches": False}, {"plan_sha256": "0" * 64}, {"action_id": "other"}, {"provenance_checked": "true"}):
            with self.assertRaises(WorkflowRefusal):
                self.engine.begin_operation(self.sid, action_id="fictional-action", plan_sha256=self.plan_hash, precondition_evidence_ids=[self.precondition(**overrides)])
        with self.assertRaises(WorkflowRefusal):
            self.engine.begin_operation(self.sid, action_id="fictional-action", plan_sha256=self.plan_hash, precondition_evidence_ids=[])
        self.assertFalse(self.state()["operations"])

    def test_approval_does_not_allow_reusing_stale_preconditions(self):
        self.apply_ready()
        precondition = self.precondition()
        later = (datetime.now(timezone.utc) + timedelta(minutes=16)).isoformat().replace("+00:00", "Z")
        with mock.patch("pc_records.utc_now", return_value=later):
            with self.assertRaises(WorkflowRefusal):
                self.engine.begin_operation(self.sid, action_id="fictional-action", plan_sha256=self.plan_hash, precondition_evidence_ids=[precondition])
        self.assertFalse(self.state()["operations"])

    def test_operation_receipt_one_use_and_finish_needs_owned_actual_outcome(self):
        self.apply_ready()
        operation_id = self.begin()
        with self.assertRaises(WorkflowRefusal):
            self.begin()
        with self.assertRaises(WorkflowRefusal):
            self.engine.finish_operation(self.sid, operation_id=operation_id, outcome="succeeded", evidence_ids=[], summary="A model says success")
        wrong = self.evidence("outcome", {"operation_id": "wrong-operation", "action_id": "fictional-action", "plan_sha256": self.plan_hash, "outcome": "succeeded"})
        with self.assertRaises(WorkflowRefusal):
            self.engine.finish_operation(self.sid, operation_id=operation_id, outcome="succeeded", evidence_ids=[wrong], summary="Wrong receipt")
        self.finish(operation_id)
        with self.assertRaises(WorkflowRefusal):
            self.finish(operation_id)
        with self.assertRaises(WorkflowRefusal):
            self.begin()
        with self.assertRaises(WorkflowRefusal):
            self.engine.register_plan(self.sid, plan=self.plan)

    def test_pause_active_prevents_new_actions_and_waits_for_safe_receipt(self):
        self.apply_ready()
        operation_id = self.begin()
        self.engine.pause(self.sid)
        self.assertEqual(self.state()["status"], "pause_pending")
        with self.assertRaises(WorkflowRefusal):
            self.begin()
        with self.assertRaises(WorkflowRefusal):
            self.engine.resume(self.sid, reconciliation_evidence_ids=[self.reconciliation()])
        self.finish(operation_id)
        self.assertEqual(self.state()["status"], "paused")
        with self.assertRaises(WorkflowRefusal):
            self.engine.resume(self.sid, reconciliation_evidence_ids=[])
        self.engine.resume(self.sid, reconciliation_evidence_ids=[self.reconciliation()])
        self.assertEqual(self.state()["status"], "active")

    def test_pause_without_operation_still_requires_fresh_actual_state_reconciliation(self):
        old = self.reconciliation()
        self.engine.pause(self.sid)
        with self.assertRaises(WorkflowRefusal):
            self.engine.resume(self.sid, reconciliation_evidence_ids=[old])
        wrong = self.evidence("reconciliation", {"scope_matches": True, "no_changes_detected": True, "operation_outcomes": {"invented": "succeeded"}, "plan_sha256": None})
        with self.assertRaises(WorkflowRefusal):
            self.engine.resume(self.sid, reconciliation_evidence_ids=[wrong])
        self.engine.resume(self.sid, reconciliation_evidence_ids=[self.reconciliation()])

    def test_stop_preserves_evidence_and_does_not_reopen_after_active_receipt(self):
        for outcome in ("succeeded", "failed", "partial", "unknown"):
            self.engine = WorkflowEngine(self.root, work_relative="work/stopped-" + outcome)
            self.sid = self.engine.create_session(scope=self.scope, checkpoints=[])["session_id"]
            self.apply_ready()
            operation_id = self.begin()
            self.engine.stop(self.sid)
            with self.assertRaises(WorkflowRefusal):
                self.evidence("inventory", {"item_count": 1})
            ids = [] if outcome == "unknown" else [self.outcome(operation_id, outcome)]
            self.engine.finish_operation(self.sid, operation_id=operation_id, outcome=outcome, evidence_ids=ids, summary="Fictional receipt after stop")
            self.assertEqual(self.state()["status"], "stopped")
            with self.assertRaises(WorkflowRefusal):
                self.engine.resume(self.sid, reconciliation_evidence_ids=[])
            with self.assertRaises(WorkflowRefusal):
                self.begin()
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("cannot-reopen")

    def test_registry_outstanding_ticket_blocks_other_session_and_schedule_until_stopped_outcome_reconciles(self):
        self.apply_ready()
        first_id, first_hash, first_plan = self.sid, self.plan_hash, self.plan
        operation_id = self.begin()
        self.engine.pause(first_id)
        self.sid = self.engine.create_session(scope=self.scope, checkpoints=[])["session_id"]
        self.apply_ready()
        second_id, second_hash, second_plan = self.sid, self.plan_hash, self.plan
        with self.assertRaisesRegex(WorkflowRefusal, "outstanding mutating operation"):
            self.begin()
        scheduled_id = self.engine.create_session(scope=self.scope, timing="scheduled", checkpoints=[])["session_id"]
        due = datetime.now(timezone.utc) + timedelta(minutes=1)
        self.engine.configure_schedule(scheduled_id, schedule={"when_utc": due.isoformat().replace("+00:00", "Z"), "description": "Fictional dispatch must wait for the earlier operation"}, owner_quote="Record this fictional proposal.", owner_message_id="fictional-other-schedule")
        with mock.patch("pc_records.utc_now", return_value=(due + timedelta(seconds=1)).isoformat().replace("+00:00", "Z")):
            with self.assertRaisesRegex(WorkflowRefusal, "outstanding mutating operation"):
                self.schedule_trigger("blocked-by-pause-pending", session_id=scheduled_id)
        self.engine.stop(first_id)
        self.sid, self.plan_hash, self.plan = first_id, first_hash, first_plan
        self.finish(operation_id, "unknown")
        self.sid, self.plan_hash, self.plan = second_id, second_hash, second_plan
        with self.assertRaisesRegex(WorkflowRefusal, "outstanding mutating operation"):
            self.begin()
        self.sid, self.plan_hash, self.plan = first_id, first_hash, first_plan
        observed = self.outcome(operation_id, "succeeded", "reconciliation")
        pending_id = self.engine.resolve(first_id)["data"]["pending"][0]["pending_id"]
        self.engine.resolve(first_id, pending_id=pending_id, evidence_ids=[observed])
        self.assertEqual(self.state()["status"], "stopped")
        self.sid, self.plan_hash, self.plan = second_id, second_hash, second_plan
        self.begin()

    def test_registry_atomic_start_allows_only_one_mutating_ticket_across_concurrent_sessions(self):
        self.apply_ready()
        first = (self.sid, self.plan_hash, self.precondition())
        self.sid = self.engine.create_session(scope=self.scope, checkpoints=[])["session_id"]
        self.apply_ready()
        second = (self.sid, self.plan_hash, self.precondition())
        barrier = threading.Barrier(2)
        def attempt(inputs):
            barrier.wait(timeout=10)
            try:
                return self.engine.begin_operation(inputs[0], action_id="fictional-action", plan_sha256=inputs[1], precondition_evidence_ids=[inputs[2]])
            except WorkflowRefusal as error:
                return str(error)
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(attempt, (first, second)))
        self.assertEqual(sum(isinstance(result, dict) for result in results), 1)
        self.assertEqual(sum(len(self.engine.read_session(inputs[0])["operations"]) for inputs in (first, second)), 1)

    def test_paused_success_and_unknown_reconciliation_keep_exact_action_checkpoints(self):
        outer = self.root
        for outcome in ("succeeded", "unknown"):
            with self.subTest(outcome=outcome):
                self.root = outer / ("fictional-paused-" + outcome)
                self.root.mkdir()
                self.engine = WorkflowEngine(self.root)
                self.sid = self.engine.create_session(scope=self.scope, checkpoints=["before_action", "after_action"])["session_id"]
                self.sequence = 0
                self.plan_ready()
                plan = copy.deepcopy(self.plan)
                second = copy.deepcopy(plan["actions"][0])
                second["action_id"] = "fictional-second-action"
                plan["actions"].append(second)
                self.plan = plan
                self.plan_hash = self.engine.register_plan(self.sid, plan=plan)["data"]["plan_sha256"]
                for reviewer, role in (("paused-reviewer-a", "compatibility_data"), ("paused-reviewer-b", "evidence_security")):
                    self.engine.record_review(self.sid, plan_sha256=self.plan_hash, reviewer_id=reviewer, role=role, verdict="approved", evidence_ids=[self.evidence("review", {"checked": True})], notes="Review this exact fictional two-action plan")
                self.engine.approve_plan(self.sid, plan_sha256=self.plan_hash, action_ids=["fictional-action", "fictional-second-action"], owner_quote="Approve only these two fictional actions in order.", owner_message_id="fictional-paused-two-actions")
                self.engine.advance_stage(self.sid, evidence_ids=[])
                before_a = self.engine.resolve(self.sid)["data"]["pending"][0]
                self.engine.resolve(self.sid, pending_id=before_a["pending_id"], choice="continue", owner_quote="Continue only action A.", owner_message_id="fictional-before-a")
                operation = self.begin()
                self.engine.pause(self.sid)
                self.finish(operation, outcome)
                if outcome == "unknown":
                    reconciliation = next(item for item in self.engine.resolve(self.sid)["data"]["pending"] if item["kind"] == "reconciliation")
                    self.engine.resolve(self.sid, pending_id=reconciliation["pending_id"], evidence_ids=[self.outcome(operation, "succeeded", "reconciliation")])
                self.assertEqual(self.state()["status"], "paused")
                pending = self.engine.resolve(self.sid)["data"]["pending"]
                self.assertEqual({(item["checkpoint"], item["action_id"]) for item in pending}, {("after_action", "fictional-action"), ("before_action", "fictional-second-action")})
                self.engine.resume(self.sid, reconciliation_evidence_ids=[self.reconciliation()])
                self.assertEqual(self.state()["status"], "awaiting_user")
                facts = {"action_id": second["action_id"], "plan_sha256": self.plan_hash, "identity_matches": True, "scope_matches": True, "content_matches": True, "compatibility_checked": True, "provenance_checked": True, **{key: second[key] for key in ("adapter_id", "adapter_payload_sha256", "adapter_plan_sha256", "target_inventory_sha256")}}
                evidence = self.evidence("precondition", facts)
                with self.assertRaises(WorkflowRefusal):
                    self.engine.begin_operation(self.sid, action_id=second["action_id"], plan_sha256=self.plan_hash, precondition_evidence_ids=[evidence])
                for index, item in enumerate(pending):
                    self.engine.resolve(self.sid, pending_id=item["pending_id"], choice="continue", owner_quote="Review the actual A result and the exact next B action.", owner_message_id="fictional-checkpoint-" + str(index))
                tokens = set(self.state()["pending"])
                self.engine.pause(self.sid)
                self.engine.resume(self.sid, reconciliation_evidence_ids=[self.reconciliation()])
                self.assertEqual(set(self.state()["pending"]), tokens)
                operation_b = self.engine.begin_operation(self.sid, action_id=second["action_id"], plan_sha256=self.plan_hash, precondition_evidence_ids=[evidence])["data"]["operation_id"]
                self.engine.stop(self.sid)
                late = self.evidence("outcome", {"operation_id": operation_b, "action_id": second["action_id"], "plan_sha256": self.plan_hash, "outcome": "succeeded"})
                self.engine.finish_operation(self.sid, operation_id=operation_b, outcome="succeeded", evidence_ids=[late], summary="Actual stopped late B result")
                self.assertEqual(self.state()["status"], "stopped")
                self.assertEqual(set(self.state()["pending"]), tokens)


