class RestartStateTests(PackagePlanHelpers, WorkflowFixture):
    """The status and options texts and the report follow one reading of a restart record, on a session driven through the
    real engine; the report takes engine_journal.restart_state as data, as the service passes it."""

    def setUp(self):
        super().setUp()
        self.batch([], [])
        self.operation_id = self.start("fictional-a1")

    def signal(self, signal, source):
        operation = self.state()["operations"][self.operation_id]
        row = self.evidence("outcome", {key: operation[key] for key in ("operation_id", "action_id", "plan_sha256")}
                            | {"outcome": "unknown", "restart_signal": signal, "restart_source": source})
        self.allowed(self.engine.record_restart_pending, self.sid, operation_id=self.operation_id, evidence_id=row)

    def shown(self):
        """(status text, options text, the step's report row) of the session as it is now."""
        state = self.state()
        restarts = {key: engine_journal.restart_state(operation) for key, operation in state["operations"].items()}
        page = report.render_session(state, restarts=restarts, labels=engine_text.report_labels()).decode("utf-8")
        record = pc_records.decode_strict(re.search(r'id="report-data">(.*?)</script>', page, re.S)[1].encode("ascii"))
        rows = [dict(content) for kind, content in record["outcomes"] if kind == "fields"]
        return self.engine.status(self.sid)["message"], self.engine.options(self.sid)["message"], rows[0]

    def assert_waits(self, expected):
        status, options, row = self.shown()
        for message in (status, options):
            self.assertEqual(engine_text.RESTART_WAIT in message, expected)
        self.assertEqual(row["Result"] == report.RESTART_WAITING, expected)

    def test_a_signal_read_again_as_gone_ends_the_wait_everywhere(self):
        self.signal("required", "linux.reboot_required")
        self.assertEqual(engine_journal.restart_state(self.state()["operations"][self.operation_id]), "waiting")
        self.assert_waits(True)
        self.signal("none", "linux.reboot_required")
        operation = self.state()["operations"][self.operation_id]
        self.assertEqual((engine_journal.restart_state(operation), operation["outcome"]), ("none", None))
        self.assert_waits(False)
        self.assertEqual(self.outstanding(), [(None, False)])  # the engine agrees: the step is in flight, not in the restart class
        self.assertEqual(self.shown()[2]["Restart signal"], "No restart reported (none); reported by linux.reboot_required")

    def test_an_observed_boot_ends_the_wait_and_the_result_stays_open(self):
        self.signal("required", "exit_code")
        self.assert_waits(True)
        observed = pc_records.utc_now()
        boot = {"schema": "patchcairn.boot.observation", "schema_version": 1, "last_boot_utc": observed, "boot_id": "fictional-boot-2",
                "observed_utc": observed, "source": "fictional.boot_probe"}
        operation = self.state()["operations"][self.operation_id]
        self.engine.register_evidence(self.sid, evidence_id="fictional-boot", content=pc_records.encoded(boot), kind="outcome", scope=self.scope, observed_utc=observed,
                                      facts={key: operation[key] for key in ("operation_id", "action_id", "plan_sha256")} | {"outcome": "unknown"})
        self.allowed(self.engine.record_boot_observation, self.sid, operation_id=self.operation_id, evidence_id="fictional-boot")
        operation = self.state()["operations"][self.operation_id]
        self.assertEqual((engine_journal.restart_state(operation), operation["outcome"]), ("boot_observed", None))
        self.assert_waits(False)
        row = self.shown()[2]
        self.assertEqual(row["Result"], report.NO_RESULT)  # "verification finished" is the outcome, a separate fact
        self.assertTrue(row["Restart seen"].startswith("A later start of the computer was recorded"))


