class HumanMessageTests(unittest.TestCase):
    """Render fictional state only; no engine namespace or host operation."""
    def setUp(self):
        self.state = {"session_id": "fictional-message", "revision": 1, "job": "diagnosis_repair", "stage": "hypotheses", "status": "active", "mode": "real", "settings": {"control": "guided", "timing": "now"}, "plan": None, "pending": {}, "operations": {}}
        self.engine = object.__new__(WorkflowEngine)
        self.engine.read_session = mock.Mock(side_effect=lambda unused: copy.deepcopy(self.state))

    def test_terminal_status_explains_closure_and_preserves_unknown_outcome(self):
        self.state.update(status="stopped", operations={"fictional-operation": {"outcome": "unknown"}})
        before = copy.deepcopy(self.state)
        stopped = self.engine.status("fictional-message")
        self.assertIn("cannot resume", stopped["message"])
        self.assertIn("does not prove it finished", stopped["message"])
        self.assertEqual(stopped["data"]["operations"][0]["outcome"], "unknown")
        self.assertNotIn("blocked until", stopped["message"])
        self.assertEqual(self.state, before)
        self.state.update(status="completed", stage="complete", operations={})
        completed = self.engine.status("fictional-message")
        self.assertIn("result checks are complete", completed["message"])
        self.assertIn("session is closed", completed["message"])
        self.assertNotIn("reconciled", completed["message"])
        self.assertNotIn("Request fresh outcome checks", self.engine.options("fictional-message")["message"])

    def test_pause_pending_and_real_mode_do_not_imply_approval_or_known_result(self):
        self.state.update(status="pause_pending", stage="apply", operations={"fictional-operation": {"outcome": None}})
        result = self.engine.status("fictional-message")
        self.assertIn("safe checkpoint", result["message"])
        self.assertIn("not killed", result["message"])
        self.assertIn("may still be unknown", result["message"])
        self.assertIn("does not collect evidence or approve computer changes", result["message"])
        self.assertEqual(result["data"]["status"], "pause_pending")
        self.assertEqual(set(result["data"]), {"job", "stage", "status", "control", "timing", "pending", "operations"})

    def test_unknown_costs_use_plain_labels_without_invented_quantities(self):
        result = self.engine.cost("fictional-message")
        self.assertEqual(result["data"]["estimates"], {})
        self.assertEqual(result["data"]["unknown"], ["duration_minutes", "money", "bytes"])
        self.assertIn("Still unknown: time, price, data workload", result["message"])
        self.assertIn("does not tell you how much disk space will be freed", result["message"])
        self.assertNotIn("owned plan/inventory", result["message"])
        self.assertNotIn("duration_minutes", result["message"])
        self.assertNotRegex(result["message"], r"\b\d+(?:\.\d+)?\s*(?:minutes|USD|bytes)\b")

    def test_known_costs_show_currency_and_keep_structured_metrics(self):
        self.state["plan"] = {"document": {"actions": [{"estimate_evidence_id": "a"}, {"estimate_evidence_id": "b"}]}}
        facts = {"a": {"duration_minutes": 3, "money": 2, "currency": "USD", "bytes": 100}, "b": {"duration_minutes": 4, "money": 3, "currency": "USD", "bytes": 200}}
        self.engine.evidence_rows = mock.Mock(side_effect=lambda state, ids, **kwargs: [{"facts": facts[ids[0]]}])
        result = self.engine.cost("fictional-message")
        self.assertEqual(result["data"]["estimates"], {"duration_minutes": 7, "money": 5, "currency": "USD", "bytes": 300})
        self.assertIn("Estimated time: 7 minutes", result["message"])
        self.assertIn("Estimated price: 5 USD", result["message"])
        self.assertIn("Recorded data workload: 300 bytes", result["message"])
        facts["b"]["currency"] = "EUR"
        mixed = self.engine.cost("fictional-message")
        self.assertIn("money", mixed["data"]["unknown"])
        self.assertNotIn("Estimated price:", mixed["message"])

    def test_options_describe_actual_checkpoint_with_human_stage_and_choices(self):
        self.state.update(status="awaiting_user", pending={"fictional-stop": {"kind": "checkpoint", "checkpoint": "findings", "action_id": None, "resolved": False}})
        result = self.engine.options("fictional-message")
        self.assertIn("compare possible causes", result["message"])
        self.assertIn("Your chosen stop is the assessment findings", result["message"])
        self.assertIn("Choices:", result["message"])
        self.assertIn("Inspect this chosen stop with PatchCairn: resolve", result["message"])
        self.assertNotIn("hypotheses", result["message"])
        self.assertIn("does not approve unreviewed changes", result["message"])

    def test_unknown_outcome_options_require_actual_observation(self):
        self.state.update(status="held", pending={"fictional-unknown": {"kind": "reconciliation", "resolved": False}})
        result = self.engine.options("fictional-message")
        self.assertIn("unknown result cannot be treated as success or retried", result["message"])
        self.assertIn("collect fresh evidence of what actually happened", result["message"])

    def test_restart_pending_messages_distinguish_installer_exit_from_behavior(self):
        self.state.update(job="security_updates", stage="apply", status="pause_pending", operations={"fictional-operation": {"outcome": None, "restart_pending": {"original_exit_code": 3010}}}, pending={"restart-fictional": {"kind": "restart", "resolved": False, "operation_id": "fictional-operation"}})
        result = self.engine.status("fictional-message")
        self.assertIn("installer finished", result["message"])
        self.assertIn("still unverified", result["message"])
        self.assertIn("No restart or installer retry happens automatically", result["message"])
        self.assertNotIn("installer is still running", result["message"])
        options = self.engine.options("fictional-message")
        self.assertIn("defer this exact restart", options["message"])
        self.assertIn("authorize the owner-handled restart", options["message"])
        self.assertIn("unsaved work", options["message"])
        self.assertIsNone(result["data"]["operations"][0]["outcome"])
        self.state["status"] = "stopped"
        self.state["pending"]["reconcile-fictional"] = {"kind": "reconciliation", "resolved": False, "operation_id": "fictional-operation"}
        stopped = self.engine.options("fictional-message")
        self.assertIn("account for this retained operation", stopped["message"])
        self.assertIn("session stays stopped", stopped["message"])
        inspected = self.engine.resolve("fictional-message")
        self.assertEqual(inspected["data"]["choices"], ["keep_stopped", "defer", "authorize"])
        self.assertIn("retained original 3010 operation only", inspected["message"])


class WorkflowTests(WorkflowFixture):
    def test_initial_menu_has_attribution_jobs_control_timing_and_every_namespaced_command(self):
        menu = initial_menu()
        self.assertTrue(menu.startswith("PatchCairn — Developed by Michael"))
        for job, row in JOBS.items():
            self.assertIn(row["label"], menu)
            self.assertNotIn(job, menu)
        for command in COMMANDS:
            self.assertIn("PatchCairn: " + command, menu)
        self.assertIn("independent", menu)
        self.assertIn("Credentials", menu)
        for phrase in ("whole-device assessment", "selected drives or folders", "local content reads", "shared with the assistant", "excluded by default", "OS permissions"):
            self.assertIn(phrase, menu)
        for phrase in ("I recommend guided", "read-only assessment", "Checkpoints are chosen stops", "A plan is a clear list", "Automatic control has fewer pauses", "assistant usage costs", "Time, download size"):
            self.assertIn(phrase, menu)
        self.assertNotIn("JSON", menu)
        self.assertNotIn("SHA", menu)
        self.assertNotIn("/resume", menu)

    def test_catalog_template_matches_fixed_code_catalog(self):
        template = pc_records.decode_strict((ROOT / "templates" / "workflows.json").read_bytes())
        self.assertIs(pc_records.require_container(template, "workflows_template"), template)
        self.assertEqual(template["backend"], BACKEND)
        self.assertEqual(template["jobs"], JOBS)
        self.assertEqual(template["commands"], list(COMMANDS))
        self.assertEqual(set(template["checkpoints"]), CHECKPOINTS)

    def test_tool_catalog_and_toolkit_marker_are_strict_containers(self):
        catalog = pc_records.decode_strict((ROOT / "templates" / "tool-catalog.json").read_bytes())
        self.assertIs(pc_records.require_container(catalog, "tool_catalog"), catalog)
        self.assertEqual(catalog["catalog_kind"], "documentation_only")
        toolkit = pc_records.decode_strict((ROOT / "toolkit.json").read_bytes())
        self.assertIs(pc_records.require_container(toolkit, "toolkit_marker"), toolkit)
        self.assertEqual((toolkit["name"], toolkit["version"]), ("PatchCairn", "1.0.0"))
        for retired in ("session-contract.json", "host-adapters.json"):
            self.assertFalse((ROOT / "templates" / retired).exists())

    def test_parser_refuses_ambiguity_and_borrowed_host_commands(self):
        self.assertEqual(parse_command("/resume")["code"], "foreign_command")
        self.assertEqual(parse_command("please maybe clean or diagnose")["code"], "ambiguous_command")
        self.assertFalse(parse_command("PatchCairn: start storage_cleanup diagnosis_repair")["ok"])
        self.assertFalse(parse_command("PatchCairn: status; whoami")["ok"])
        self.assertFalse(parse_command("PatchCairn: settings control=guided control=automatic")["ok"])
        self.assertFalse(parse_command("PatchCairn: pause and delete backups")["ok"])
        self.assertEqual(parse_command("start assessment")["command"], "start")
        self.assertEqual(parse_command("PatchCairn: start 2")["arguments"], ["storage_cleanup"])

    def test_bare_start_displays_menu_without_allocating_a_session(self):
        before = list(self.engine.work.iterdir())
        result = self.engine.dispatch(None, "PatchCairn: start")
        self.assertIsNone(result["session_id"])
        self.assertEqual(before, list(self.engine.work.iterdir()))
        self.assertIn("creates no session", result["message"])

    def test_cost_unknown_is_not_invented_and_decision_card_has_required_fields(self):
        result = self.engine.cost(self.sid)
        self.assertEqual(result["data"]["estimates"], {})
        self.assertEqual(set(result["data"]["unknown"]), {"duration_minutes", "money", "bytes"})
        card = self.engine.options(self.sid)["data"]["decision"]
        self.assertEqual(set(card), {"meaning", "benefits", "drawbacks", "cost", "reversibility", "recommendation", "options"})


