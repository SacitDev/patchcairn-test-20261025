class MenuTests(unittest.TestCase):
    def test_menu_keeps_title_four_job_rows_checkpoint_list_and_every_command(self):
        menu = initial_menu()
        self.assertTrue(menu.startswith("PatchCairn — Developed by Michael\n"))
        self.assertEqual(JOB_ROW.findall(menu), [row["label"] for row in JOBS.values()])
        listed = [name.strip() for name in re.split(r",\s*(?:and\s+)?|\s+and\s+", CHECKPOINT_LIST.search(menu)[1])]
        self.assertEqual(listed, ["scope", "findings", "plan", "before each action", "after each action", "finish"])
        self.assertEqual({name.replace(" each ", "_") for name in listed}, CHECKPOINTS)
        for command in COMMANDS:
            with self.subTest(command=command):
                self.assertEqual(len(re.findall(r"(?m)^PatchCairn: " + command + r" \(", menu)), 1)
        self.assertEqual(set(re.findall(r"PatchCairn: ([a-z]+)", menu)), set(COMMANDS))
        for phrase in ("guided", "automatic", "now or scheduled", "Privacy:", "never ask for passwords", "Cost:", "whole device",
                       "selected drives or folders", "one problem", "Showing this menu changes nothing."):
            self.assertIn(phrase, menu)
        for job in JOBS:
            self.assertNotIn(job, menu)
        for absent in ("JSON", "SHA", "/resume", "quarantine"):
            self.assertNotIn(absent, menu)

    def test_menu_at_most_320_words(self):
        self.assertLessEqual(words(initial_menu()), 320)

    def test_help_is_not_the_menu_and_at_most_160_words(self):
        help_text = engine_text.help_text()
        self.assertNotEqual(help_text, initial_menu())
        self.assertNotIn(help_text, initial_menu())
        self.assertEqual(JOB_ROW.findall(help_text), [])
        self.assertLessEqual(words(help_text), 160)
        for phrase in ("PatchCairn: status", "PatchCairn: pause", "PatchCairn: resume", "PatchCairn: stop", '"done"', 'plain "yes" never approves'):
            self.assertIn(phrase, help_text)
        # In a session and without one, PatchCairn: help answers with the help text, never the menu.
        engine = fake_engine(fictional_state())
        for session_id in (None, "fictional-message"):
            with self.subTest(session=session_id):
                answer = engine_text.dispatch(engine, session_id, "PatchCairn: help")
                self.assertEqual((answer["code"], answer["message"]), ("help", help_text))


class ParseTests(unittest.TestCase):
    def test_bare_number_after_menu_starts_that_job(self):
        for number, job in enumerate(JOBS, 1):
            for text in (str(number), " " + str(number) + " ", "PatchCairn: " + str(number), str(number) + "."):
                with self.subTest(text=text):
                    self.assertEqual(parse_command(text), {"ok": True, "command": "start", "arguments": [job]})
        for text in ("0", "5", "12", "2 3", "-1"):
            with self.subTest(text=text):
                self.assertFalse(parse_command(text)["ok"])
        engine = fake_engine(fictional_state())
        engine_text.dispatch(engine, None, "2")
        engine.create_session.assert_called_once_with(job="storage_cleanup")

    def test_fixed_phrases_map_to_jobs(self):
        cases = {"free up space": "storage_cleanup", "clean up my disk": "storage_cleanup", "update everything": "security_updates",
                 "update my computer": "security_updates", "my computer is slow": "diagnosis_repair", "back up my files": "backup_recovery",
                 "Free Up Space": "storage_cleanup", "  clean   up my disk ": "storage_cleanup", "Update everything!": "security_updates",
                 "PatchCairn: update my computer": "security_updates", "my computer is slow.": "diagnosis_repair",
                 "my disk is full": "storage_cleanup", "check for updates": "security_updates", "restore my files": "backup_recovery"}
        for text, job in cases.items():
            with self.subTest(text=text):
                self.assertEqual(parse_command(text), {"ok": True, "command": "start", "arguments": [job]})
        for phrase, command in engine_text.PHRASES.items():
            with self.subTest(phrase=phrase):
                self.assertTrue(parse_command(phrase)["ok"], phrase)
                self.assertIn(command.split()[0], COMMANDS)

    def test_unknown_text_stays_ambiguous(self):
        for text in ("please maybe clean or diagnose", "please free up some space", "free up space and update everything", "free", "yes",
                     "approve", "delete 3 files", "go ahead", "update", "done and approve", "done, resume", "I am done with it", "my computer"):
            with self.subTest(text=text):
                self.assertEqual(parse_command(text)["code"], "ambiguous_command")
        self.assertEqual(parse_command("start everything")["code"], "ambiguous_job")

    def test_done_maps_to_status(self):
        for text in ("done", "Done.", "PatchCairn: done", "  DONE "):
            with self.subTest(text=text):
                self.assertEqual(parse_command(text), {"ok": True, "command": "status", "arguments": []})
        # "done" only reads the session: it never approves, resumes or changes anything.
        state = fictional_state(status="paused")
        engine = fake_engine(state)
        engine.resume = engine.approve_plan = engine.resolve = mock.Mock(side_effect=AssertionError("done must only check"))
        answer = engine_text.dispatch(engine, "fictional-message", "done")
        self.assertEqual((answer["code"], answer["revision"]), ("status", state["revision"]))
        engine.change.assert_not_called()

    def test_start_assessment_shows_the_menu_not_a_job(self):
        self.assertEqual(parse_command("start assessment"), {"ok": True, "command": "start", "arguments": []})
        engine = fake_engine(fictional_state())
        answer = engine_text.dispatch(engine, None, "PatchCairn: start assessment")
        self.assertEqual((answer["code"], answer["session_id"], answer["message"]), ("menu", None, initial_menu()))
        engine.create_session.assert_not_called()

    def test_resume_settings_and_resolve_messages_are_plain(self):
        state = fictional_state(status="paused", settings={"control": "guided", "timing": "now", "checkpoints": ["scope", "plan"]})
        engine = fake_engine(state)
        resume = engine_text.dispatch(engine, "fictional-message", "PatchCairn: resume")
        self.assertEqual(resume["code"], "reconciliation_required")
        self.assertTrue(resume["message"].endswith("Before carrying on, I first check what actually happened while work was paused. "
                                                   "Nothing has started again yet."))
        settings = engine_text.dispatch(engine, "fictional-message", "PatchCairn: settings")["message"]
        self.assertIn("Your settings now: control guided, timing now, checkpoints scope, plan.", settings)
        bad = parse_command("PatchCairn: settings guided")["message"]
        resolve = parse_command("PatchCairn: resolve the restart please")["message"]
        self.assertEqual(resolve, "Say PatchCairn: resolve on its own and I will show what is waiting for your decision. It takes no other words.")
        for message in (resume["message"], settings, bad, resolve):
            for jargon in ("coordinator", "reconcil", "owned", "evidence", "identifier", "free-form", "invalidate"):
                self.assertNotIn(jargon, message.lower())
        # Each example the messages give is accepted by the parser.
        for example in re.findall(r"PatchCairn: (settings(?: [a-z_]+=[a-z_,]+)+)", settings + " " + bad):
            with self.subTest(example=example):
                self.assertTrue(parse_command(example)["ok"])
        for example in ("settings control=automatic", "settings timing=scheduled", "settings checkpoints=scope,findings,plan,before_action,after_action,finish"):
            self.assertTrue(parse_command(example)["ok"])
        self.assertTrue(parse_command("PatchCairn: resolve")["ok"])


class TextTests(unittest.TestCase):
    def test_deletion_warning_names_count_bytes_reply_and_three_facts(self):
        text = engine_text.deletion_warning(warning("delete_selected", 2341, 1_234_567_890))
        self.assertIn("deletes 2341 files for good (about 1.2 GB)", text)
        for fact in ("skip the Recycle Bin or Trash", "no copy is kept", "this is not secure erasure"):
            self.assertIn(fact, text)
        self.assertEqual(text.count(engine_text.irreversible_phrase("delete_selected", 2341)), 1)
        self.assertIn("type exactly: delete 2341 files\n", text)
        self.assertIn('a plain "yes" does not approve this', text)
        for banned in ("erase ", "wipe", "purge", "remove permanently", "securely", "2,341"):
            self.assertNotIn(banned, text.lower())
        purge = engine_text.deletion_warning(warning("permanent_purge", 3, 512))
        self.assertIn("deletes 3 set-aside files for good (512 bytes)", purge)
        self.assertIn("no copy is kept", purge)
        backups = engine_text.deletion_warning(warning("retention_release", 2, 5_000_000))
        self.assertIn("type exactly: delete 2 backups", backups)
        # Removing originals after a checked backup keeps that backup: the text says so instead of "no copy is kept".
        originals = engine_text.deletion_warning(warning("remove_originals", 4, 4000))
        self.assertIn("the checked backup becomes the only copy", originals)
        self.assertNotIn("no copy is kept", originals)
        for bad in (warning("firmware_update", 2, None), warning("delete_selected", 0, 1), warning("delete_selected", 2, -1),
                    warning("delete_selected", True, 1), warning("cleanup_quarantine", 2, 1), "delete 2 files"):
            with self.subTest(bad=bad), self.assertRaises(WorkflowRefusal):
                engine_text.deletion_warning(bad)

    def test_firmware_card_states_power_key_and_no_switch_off(self):
        dual_boot = ("If this computer can also start Windows, have the Windows BitLocker recovery key too (usually in your Microsoft "
                     "account).")
        linux = engine_text.firmware_warning(warning("firmware_update", 2, None), platform="linux", device="Fictional\u202e Disk",
                                             flags=["firmware", "high_risk"])
        for phrase in ("wall socket", "On battery", "checks the power again just before it starts", "do not switch off",
                       "the device may stop working while it updates", "back up the files on that drive first", "recovery key",
                       "passphrase", dual_boot.lower(), "only after the check that follows the restart", "no second copy"):
            self.assertIn(phrase.lower(), linux.lower())
        self.assertIn('What this does: updates the firmware (the built-in software) of device 2 ("Fictional Disk").\n', linux)
        self.assertNotIn("Device:", linux)
        self.assertIn("type exactly: update firmware on device 2, I have my recovery key\n", linux)
        self.assertNotIn(dual_boot, engine_text.firmware_card("linux", uefi_or_fde=False))
        self.assertIn("second copy of its firmware, which may let it recover", engine_text.firmware_card("linux", flags=["dual_image"]))
        windows = engine_text.firmware_card("windows")
        self.assertIn("https://aka.ms/myrecoverykey", windows)
        self.assertIn("suspending BitLocker", windows)
        self.assertIn("PatchCairn never does it", windows)
        self.assertNotIn(dual_boot, windows)
        mac = engine_text.firmware_card("macos")
        self.assertIn("PatchCairn cannot tell whether this macOS update also updates the Mac's firmware", mac)
        self.assertIn("FileVault", mac)
        # Unknown facts give every precaution: all three keys and the dual-boot line.
        unknown = engine_text.firmware_warning(warning("firmware_update", 1, None))
        for phrase in ("BitLocker recovery key", "FileVault", "passphrase", dual_boot):
            self.assertIn(phrase, unknown)
        for bad in (dict(warning("firmware_update", 1, None), kind="delete_selected"), warning("firmware_update", 0, None)):
            with self.subTest(bad=bad), self.assertRaises(WorkflowRefusal):
                engine_text.firmware_warning(bad)
