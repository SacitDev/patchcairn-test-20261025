# The word pattern, the menu's job rows and the checkpoint list, read from the menu the same way the docs check reads them.
WORD = re.compile(r"[A-Za-z0-9][A-Za-z0-9'\u2019-]*")
JOB_ROW = re.compile(r"(?m)^\s*(?:\|\s*)?(?:\*\*)?\s*[1-4]\.\s*([^:*|\n]+?)\s*(?:\*\*)?\s*[:|]")
CHECKPOINT_LIST = re.compile(r"(?i)\bcheckpoints\b[^:.\n]*:\s*([^.\n]+)\.")
STATUSES = {"active", "awaiting_user", "held", "paused", "pause_pending", "stopped", "completed"}
# Overclaiming phrases that no product text may contain.
OVERCLAIMS = [r"records your actual decision", r"actual independent work", r"actual current owner('s)? instruction",
              r"independent (people|persons|humans)", r"distinct[ _](people|persons|humans)", r"proves? (that )?(a|the) (human|person|owner)",
              r"cryptographically prov", r"guaranteed (safe|secure)", r"completely (safe|secure)", r"100\s?% (safe|secure)",
              r"fully protected", r"(bank|military)-grade", r"verified by a (human|person)", r"your actual instruction is recorded",
              r"securely (deleted|erased|wiped)", r"(deleted|erased|wiped) securely", r"\b(is|are|were|was) shredded",
              r"guaranteed (up to date|patched)", r"(fully|completely) (up to date|patched) and (safe|secure)",
              r"all your (drivers|firmware|updates) (are|is) up to date"]


def words(text):
    """The larger of the two word counts: the word pattern and whitespace-separated pieces."""
    return max(len(WORD.findall(text)), len(text.split()))


