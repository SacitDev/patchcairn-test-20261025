    def test_restart_pending_messages_distinguish_installer_exit_from_behavior(self):
        # The typed restart signal (restart_pending = {"signal", "source"}): no owner restart decision exists.
        operation = fictional_operation(restart_pending={"signal": "required", "source": "fictional-probe"})
        self.state.update(job="security_updates", stage="apply", status="pause_pending", operations={"fictional-operation": operation})
        result = self.engine.status("fictional-message")
        self.assertIn(engine_text.RESTART_WAIT, result["message"])
        self.assertIn(engine_text.RESTART_NOTICE + ".", result["message"])
        self.assertIn("no change can start except a backup", result["message"])
        self.assertIn("PatchCairn: resume", result["message"])
        self.assertIsNone(result["data"]["operations"][0]["outcome"])
        for retired in ("3010", "defer", "authorize", "one restart at the end"):
            self.assertNotIn(retired, result["message"])
        options = self.engine.options("fictional-message")
        self.assertIn(engine_text.RESTART_WAIT, options["message"])
        self.assertIn("unsaved work", options["message"])
        for retired in ("defer this exact restart", "authorize the owner-handled restart"):
            self.assertNotIn(retired, options["message"])
        # Without a signal source the restart reads "restart: unknown", never the installer sentence.
        operation["restart_pending"] = {"signal": "required", "source": None}
        unknown = self.engine.status("fictional-message")["message"]
        self.assertIn("(" + engine_text.RESTART_UNKNOWN + ")", unknown)
        self.assertNotIn(engine_text.RESTART_NOTICE, unknown)
        # Once a later start of the computer is recorded, the operation no longer waits for a restart.
        operation["restart_verification"] = {"boot_observed": True, "evidence_id": "e", "sha256": "a" * 64, "recorded_utc": "x"}
        self.assertNotIn(engine_text.RESTART_WAIT, self.engine.status("fictional-message")["message"])
        del operation["restart_verification"]
        # A signal read again as "none" is gone: nothing asks for a restart any more.
        operation["restart_pending"] = {"signal": "none", "source": "linux.reboot_required"}
        for message in (self.engine.status("fictional-message")["message"], self.engine.options("fictional-message")["message"]):
            self.assertNotIn(engine_text.RESTART_WAIT, message)
            self.assertNotIn("restart the computer yourself", message)
        operation["restart_pending"] = {"signal": "required", "source": None}
        self.state["status"] = "stopped"
        stopped = self.engine.options("fictional-message")
        self.assertIn("Restart the computer when you are ready, then say PatchCairn: status so I can check the update. This job stays stopped.",
                      stopped["message"])
        self.assertIn("still needs a restart and a check", self.engine.status("fictional-message")["message"])


