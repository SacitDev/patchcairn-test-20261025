def posix_private_storage_capability(parent):
    """Probe only owned fictional entries; never move to another filesystem."""
    if os.name != "posix":
        return True, "POSIX permission capability is not applicable"
    parent.mkdir(parents=True, exist_ok=True)
    directory = parent / ("private-mode-probe-" + uuid.uuid4().hex)
    try:
        private_workspace.ensure_private_directory(directory, create=True)
        private_workspace.write_private_new(directory / "fixture.bin", b"Fictional permission-capability fixture")
    except private_workspace.PrivateWorkspaceError as error:
        return False, error.code
    for path, expected in ((directory, 0o700), (directory / "fixture.bin", 0o600)):
        info = path.stat()
        if info.st_uid != os.geteuid() or stat.S_IMODE(info.st_mode) != expected:
            return False, "Actual workspace does not establish current-owner private modes; no filesystem workaround"
    return True, "Actual native filesystem and current-owner POSIX directory0700/file0600 supported"


@unittest.skipUnless(os.name == "posix", "only on posix: POSIX privacy boundary; Windows uses the shared private-namespace adapter")
class PosixPrivacyTests(unittest.TestCase):
    def setUp(self):
        start_forward_only_clock(self)
        self.root = WORK / ("privacy-" + uuid.uuid4().hex)
        self.root.mkdir(parents=True)

    def capable(self):
        supported, reason = posix_private_storage_capability(self.root)
        if not supported:
            self.skipTest("only on posix: native private-storage capability is required here: " + reason)

    def engine(self, child="repository"):
        root = self.root / child
        root.mkdir()
        return WorkflowEngine(root)

    def session(self, engine):
        sid = engine.create_session(checkpoints=[])["session_id"]
        scope = engine.read_session(sid)["settings"]["scope"]
        engine.register_evidence(sid, evidence_id="fictional-private", content=b"Fictional owned evidence", kind="fixture", scope=scope)
        return sid

    def test_actual_privacy_capability_or_refusal_before_any_private_record(self):
        supported, reason = posix_private_storage_capability(self.root)
        if supported:
            self.assertTrue(supported, reason)
            return
        root = self.root / "unsupported-filesystem"
        root.mkdir()
        with self.assertRaises(PrivacyCapabilityHold):
            WorkflowEngine(root)
        self.assertFalse(list(root.rglob("engine.json")))
        self.assertFalse(list(root.rglob("session.json")))
        self.assertFalse(list(root.rglob("creation.json")))

    def test_macos_mode_bits_alone_hold_without_native_acl_admission(self):
        class DarwinHold(ValueError):
            code = "darwin-acl-present"
        acl_present = mock.Mock(side_effect=DarwinHold())
        module = types.SimpleNamespace(DarwinPrivacyHold=DarwinHold, assert_private_filesystem=mock.Mock(),
                                      assert_no_extended_acl=acl_present)
        for name, darwin_privacy, expected in (("acl", module, WorkflowRefusal), ("unavailable", None, PrivacyCapabilityHold)):
            root = self.root / ("macos-" + name)
            root.mkdir()
            with self.subTest(checker=name), mock.patch.object(sys, "platform", "darwin"), mock.patch.dict(sys.modules, {"darwin_privacy": darwin_privacy}):
                with self.assertRaisesRegex(expected, "darwin-acl"):
                    WorkflowEngine(root)
            self.assertFalse(list(root.rglob("engine.json")))
        # Owner-only mode bits on the new directory were not enough: the native ACL check refused it.
        acl_present.assert_called()

    @unittest.skipUnless(sys.platform.startswith("linux"), "only on linux: Linux native-filesystem gate")
    def test_linux_foreign_filesystem_holds_before_namespace_allocation_or_record_read(self):
        class ForeignFilesystem(ValueError):
            code = "linux-private-foreign-filesystem"
        module = types.SimpleNamespace(LinuxPrivacyHold=ForeignFilesystem,
                                      assert_native_private_filesystem=mock.Mock(side_effect=ForeignFilesystem()))
        root = self.root / "unsupported-native-filesystem"
        root.mkdir(mode=0o700)
        public_fixture = root / "fictional-record.bin"
        public_fixture.write_bytes(b"Fictional bytes which must not be read by the engine")
        # Owner-only modes, so the filesystem check alone decides.
        root.chmod(0o700)
        public_fixture.chmod(0o600)
        with mock.patch.dict(sys.modules, {"linux_privacy": module}):
            with mock.patch("engine_journal.os.mkdir", wraps=os.mkdir) as allocate:
                with self.assertRaisesRegex(PrivacyCapabilityHold, "private-linux-foreign-filesystem"):
                    WorkflowEngine(root)
                allocate.assert_not_called()
            with mock.patch("engine_journal.os.open", wraps=os.open) as opened:
                with self.assertRaisesRegex(PrivacyCapabilityHold, "private-linux-foreign-filesystem"):
                    workflow_core.read_record_bytes(public_fixture, private=True)
                opened.assert_not_called()
        self.assertFalse((root / "work").exists())
        self.assertEqual(public_fixture.read_bytes(), b"Fictional bytes which must not be read by the engine")

    def test_existing_insecure_namespace_is_held_without_chmod_or_adoption(self):
        root = self.root / "existing-insecure"
        namespace = root / "work" / "sessions"
        namespace.mkdir(parents=True)
        namespace.chmod(0o755)  # Attack fixture only, never runtime remediation.
        before = stat.S_IMODE(namespace.stat().st_mode)
        self.assertNotEqual(before, 0o700)
        with self.assertRaises(WorkflowRefusal):
            WorkflowEngine(root)
        self.assertEqual(stat.S_IMODE(namespace.stat().st_mode), before)
        self.assertFalse((namespace / "engine.json").exists())

    def test_permissive_umask_private_creation_replacement_and_locks(self):
        self.capable()
        for mask in (0, 0o022):
            old_mask = os.umask(mask)
            try:
                engine = self.engine("umask-" + str(mask))
                replacements = []
                original_replace = os.replace
                def inspect_replace(source, destination):
                    info = Path(source).stat()
                    self.assertEqual(stat.S_IMODE(info.st_mode), 0o600)
                    self.assertEqual(info.st_uid, os.geteuid())
                    replacements.append(str(source))
                    return original_replace(source, destination)
                with mock.patch("engine_journal.os.replace", side_effect=inspect_replace):
                    sid = self.session(engine)
                    engine.pause(sid)
                directory = engine.work / sid
                for path in (engine.work, directory, directory / "evidence"):
                    self.assertEqual(stat.S_IMODE(path.stat().st_mode), 0o700)
                    self.assertEqual(path.stat().st_uid, os.geteuid())
                for path in (engine.work / "engine.json", directory / "creation.json", directory / "session.json", directory / "evidence" / "fictional-private.bin"):
                    self.assertEqual(stat.S_IMODE(path.stat().st_mode), 0o600)
                    self.assertEqual(path.stat().st_uid, os.geteuid())
                with engine._lock(sid):
                    self.assertEqual(stat.S_IMODE((directory / ".lock").stat().st_mode), 0o700)
                with engine._registry_lock():
                    self.assertEqual(stat.S_IMODE((engine.work / ".registry-lock").stat().st_mode), 0o700)
                self.assertGreaterEqual(len(replacements), 3)
            finally:
                os.umask(old_mask)

    def test_live_namespace_and_record_permission_changes_are_held_unchanged(self):
        self.capable()
        for index, name in enumerate(("namespace", "marker", "session", "empty-evidence", "creation", "state", "evidence")):
            engine = self.engine("live-" + str(index))
            sid = engine.create_session(checkpoints=[])["session_id"] if name == "empty-evidence" else self.session(engine)
            directory = engine.work / sid
            paths = {"namespace": engine.work, "marker": engine.work / "engine.json", "session": directory, "empty-evidence": directory / "evidence", "creation": directory / "creation.json", "state": directory / "session.json", "evidence": directory / "evidence" / "fictional-private.bin"}
            target = paths[name]
            before = target.read_bytes() if target.is_file() else None
            target.chmod(0o755 if target.is_dir() else 0o644)
            unsafe_mode = stat.S_IMODE(target.stat().st_mode)
            with self.assertRaises(WorkflowRefusal):
                engine.read_session(sid)
            with self.assertRaises(WorkflowRefusal):
                engine.pause(sid)
            self.assertEqual(stat.S_IMODE(target.stat().st_mode), unsafe_mode)
            if before is not None:
                self.assertEqual(target.read_bytes(), before)

    def test_atomic_replacement_holds_late_insecure_destination_without_normalizing(self):
        self.capable()
        directory = self.root / "atomic-private"
        directory.mkdir(mode=0o700)
        destination = directory / "state.json"
        private_workspace.write_private_new(destination, b"Fictional original")
        original_write = private_workspace.write_private_new
        def change_destination_after_new_temp(path, data):
            original_write(path, data)
            destination.chmod(0o644)
        with mock.patch.object(private_workspace, "write_private_new", side_effect=change_destination_after_new_temp) as written:
            with self.assertRaises(WorkflowRefusal):
                workflow_core.atomic_replace(destination, b"Fictional replacement")
        written.assert_called_once()
        self.assertEqual(destination.read_bytes(), b"Fictional original")
        self.assertEqual(stat.S_IMODE(destination.stat().st_mode), 0o644)
        self.assertFalse(list(directory.glob(".write-*")))

    def test_opened_private_file_foreign_owner_is_refused_before_read(self):
        self.capable()
        engine = self.engine()
        sid = self.session(engine)
        reads = []
        original_fstat, original_fdopen = os.fstat, os.fdopen
        def foreign_owner(descriptor):
            info = original_fstat(descriptor)
            fields = {name: getattr(info, name) for name in dir(info) if name.startswith("st_")}
            fields["st_uid"] += 1
            return types.SimpleNamespace(**fields)
        class TrackedReader:
            def __init__(self, handle): self.handle = handle
            def __enter__(self): return self
            def __exit__(self, *unused): self.handle.close()
            def fileno(self): return self.handle.fileno()
            def read(self, size):
                reads.append(size)
                return self.handle.read(size)
        with mock.patch("engine_journal.os.fstat", side_effect=foreign_owner), mock.patch("engine_journal.os.fdopen", side_effect=lambda *args, **kwargs: TrackedReader(original_fdopen(*args, **kwargs))):
            with self.assertRaises(WorkflowRefusal):
                engine.read_session(sid)
        self.assertEqual(reads, [])


