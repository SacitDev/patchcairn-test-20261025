class FacadeTests(unittest.TestCase):
    """The facade that owns the journal forwards to the engine modules; nothing here touches a session."""

    def test_each_facade_method_looks_its_engine_function_up_when_called(self):
        # A patch on an engine module must reach engine.<name>, as it reaches the module's own callers.
        engine = object.__new__(WorkflowEngine)
        checked = []
        for name, entry in vars(WorkflowEngine).items():
            function = getattr(getattr(entry, "__func__", entry), "__wrapped__", None)
            if function is None:
                continue
            with mock.patch.object(sys.modules[function.__module__], function.__name__, return_value="fictional-" + name):
                self.assertEqual(getattr(engine, name)(), "fictional-" + name)
            checked.append(name)
        tree = ast.parse((ROOT / "scripts" / "workflow_core.py").read_text(encoding="utf-8"))
        facade = next(node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == "WorkflowEngine")
        wrapped = {target.id for node in facade.body if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call)
                   and getattr(node.value.func, "id", None) in ("_forward", "_static") for target in node.targets if isinstance(target, ast.Name)}
        self.assertEqual(sorted(checked), sorted(wrapped))
        self.assertIn("status", checked)
        self.assertIn("evidence_rows", checked)

    def test_facade_method_assigned_onto_its_module_calls_the_original(self):
        done = subprocess.run([sys.executable, "-I", "-S", "-B", "-c", SELF_ASSIGNED_CHILD, str(ROOT / "scripts")], capture_output=True,
                              text=True, encoding="utf-8", timeout=60)
        self.assertEqual(done.returncode, 0, done.stderr[-2000:])
        self.assertEqual(done.stdout.split(), ["static", "True", "forward", "True"])


