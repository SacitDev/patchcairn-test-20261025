class RestartAccountingGuardTests(unittest.TestCase):
    """Pure admission guard; full receipt/native-proof cases live in service tests."""
    def test_verified_restart_refuses_schedule_replacement_before_any_state_change(self):
        engine = object.__new__(WorkflowEngine)
        due = (datetime.now(timezone.utc) + timedelta(days=1)).isoformat().replace("+00:00", "Z")
        for outcome in (None, "unknown"):
            with self.subTest(outcome=outcome):
                original = {"status": "active" if outcome is None else "held", "settings": {"timing": "scheduled"}, "schedule": {"schedule_id": "original-schedule"}, "operations": {"original-operation": {"outcome": outcome, "restart_verification": {"boot_observed": True}}}}
                state = copy.deepcopy(original)
                def inspect_change(session_id, event_type, mutate, expected_revision):
                    return mutate(state)
                engine._change = inspect_change
                with self.assertRaisesRegex(WorkflowRefusal, "final receipt before changing its schedule"):
                    engine.configure_schedule("fictional-session", schedule={"when_utc": due, "description": "Delay only future work after actual result accounting"}, owner_quote="Delay the subsequent work until tomorrow.", owner_message_id="fresh-owner-delay")
                self.assertEqual(state, original)


class WorkflowTests(WorkflowFixture):
    def test_schedule_is_proposal_duplicate_trigger_and_paused_run_are_safe(self):
        self.engine.setup(self.sid, timing="scheduled")
        due = datetime.now(timezone.utc) + timedelta(minutes=1)
        self.engine.configure_schedule(self.sid, schedule={"when_utc": due.isoformat().replace("+00:00", "Z"), "description": "Fictional schedule proposal only"}, owner_quote="Record this fictional proposal, without creating an OS schedule.", owner_message_id="fictional-schedule")
        with self.assertRaises(WorkflowRefusal):
            self.schedule_trigger("fictional-trigger")
        with mock.patch("pc_records.utc_now", return_value=(due + timedelta(seconds=1)).isoformat().replace("+00:00", "Z")):
            result = self.schedule_trigger("fictional-trigger")
        self.assertFalse(result["data"]["starts_operation"])
        self.assertEqual(self.state()["status"], "awaiting_user")
        self.assertTrue(self.schedule_trigger("fictional-trigger")["data"]["duplicate"])
        self.engine.pause(self.sid)
        with self.assertRaises(WorkflowRefusal):
            self.schedule_trigger("another-trigger")
        self.assertEqual(self.state()["status"], "paused")
        self.assertFalse(self.state()["operations"])

    def test_reschedule_after_trigger_requires_current_activation_and_new_preconditions(self):
        with mock.patch("pc_records.utc_now") as clock:
            first, due = self.scheduled_apply(clock)
            old_precondition = self.precondition()
            approval = copy.deepcopy(self.state()["approval"])
            second = self.engine.configure_schedule(self.sid, schedule={"when_utc": due.isoformat().replace("+00:00", "Z"), "description": "Fictional owner delays this job"}, owner_quote="Delay this exact fictional work until the later time.", owner_message_id="fictional-schedule-second")["data"]
            self.assertEqual(self.state()["status"], "held")
            self.assertIsNone(self.state()["schedule"]["activation"])
            self.assertEqual(self.state()["approval"], approval)
            with self.assertRaises(WorkflowRefusal):
                self.begin()
            with self.assertRaises(WorkflowRefusal):
                self.engine.advance_stage(self.sid, evidence_ids=[])
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("fictional-first-trigger", schedule_id=first["schedule_id"])
            duplicate = self.schedule_trigger("fictional-first-trigger")
            self.assertTrue(duplicate["data"]["duplicate"])
            self.assertEqual(self.state()["status"], "held")
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("fictional-second-trigger")
            clock.return_value = (due + timedelta(seconds=1)).isoformat().replace("+00:00", "Z")
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("stale-owner-trigger", schedule_id=first["schedule_id"])
            self.schedule_trigger("fictional-second-trigger", schedule_id=second["schedule_id"])
            with self.assertRaises(WorkflowRefusal):
                self.engine.begin_operation(self.sid, action_id="fictional-action", plan_sha256=self.plan_hash, precondition_evidence_ids=[old_precondition])
            self.assertTrue(self.begin())

    def test_reschedule_before_trigger_rejects_stale_binding_and_owner_decision_reuse(self):
        self.engine.setup(self.sid, timing="scheduled", control="automatic")
        base = datetime.now(timezone.utc)
        first_due, second_due = base + timedelta(minutes=1), base + timedelta(minutes=2)
        first_proposal = {"when_utc": first_due.isoformat().replace("+00:00", "Z"), "description": "Fictional initial proposal"}
        first = self.engine.configure_schedule(self.sid, schedule=first_proposal, owner_quote="Use this first fictional time.", owner_message_id="fictional-first-decision")["data"]
        second_proposal = {"when_utc": second_due.isoformat().replace("+00:00", "Z"), "description": "Fictional later proposal"}
        before = self.state()
        with self.assertRaises(WorkflowRefusal):
            self.engine.configure_schedule(self.sid, schedule=second_proposal, owner_quote="Reuse an old message for a new time.", owner_message_id="fictional-first-decision")
        self.assertEqual(self.state(), before)
        second = self.engine.configure_schedule(self.sid, schedule=second_proposal, owner_quote="I choose the new later fictional time.", owner_message_id="fictional-second-decision")["data"]
        self.assertTrue(second["ready_for_trigger"])
        same = self.engine.configure_schedule(self.sid, schedule=second_proposal, owner_quote="I choose the new later fictional time.", owner_message_id="fictional-second-decision")["data"]
        self.assertEqual(same["schedule_id"], second["schedule_id"])
        with mock.patch("pc_records.utc_now", return_value=(first_due + timedelta(seconds=1)).isoformat().replace("+00:00", "Z")):
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("old-unrecorded-event", schedule_id=first["schedule_id"])
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("early-current-event")
        with mock.patch("pc_records.utc_now", return_value=(second_due + timedelta(seconds=1)).isoformat().replace("+00:00", "Z")):
            self.schedule_trigger("current-event")
            self.assertEqual(self.state()["status"], "active")
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("another-new-event")

    def test_reschedule_active_operation_keeps_safe_receipt_and_requires_reconciliation(self):
        with mock.patch("pc_records.utc_now") as clock:
            _, due = self.scheduled_apply(clock)
            operation = self.begin()
            settings_revision = self.state()["settings_revision"]
            second = self.engine.configure_schedule(self.sid, schedule={"when_utc": due.isoformat().replace("+00:00", "Z"), "description": "Fictional delay while operation awaits receipt"}, owner_quote="Pause new work and use this later fictional time.", owner_message_id="fictional-active-reschedule")["data"]
            self.assertEqual(self.state()["status"], "pause_pending")
            self.assertIsNone(self.state()["operations"][operation]["outcome"])
            self.assertEqual(self.state()["settings_revision"], settings_revision)
            self.finish(operation)
            self.assertEqual(self.state()["status"], "paused")
            clock.return_value = (due + timedelta(seconds=1)).isoformat().replace("+00:00", "Z")
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("cannot-resume-paused", schedule_id=second["schedule_id"])
            self.engine.resume(self.sid, reconciliation_evidence_ids=[self.reconciliation()])
            self.assertEqual(self.state()["status"], "held")
            with self.assertRaises(WorkflowRefusal):
                self.engine.advance_stage(self.sid, evidence_ids=[])
            self.schedule_trigger("reconciled-current-trigger")
            self.engine.advance_stage(self.sid, evidence_ids=[])
            self.assertEqual(self.state()["stage"], "verify")

    def test_reschedule_cannot_resume_unknown_or_reopen_terminal_sessions(self):
        with mock.patch("pc_records.utc_now") as clock:
            _, due = self.scheduled_apply(clock)
            operation = self.begin()
            self.finish(operation, "unknown")
            self.engine.configure_schedule(self.sid, schedule={"when_utc": due.isoformat().replace("+00:00", "Z"), "description": "Fictional delay with unknown outcome"}, owner_quote="Keep unknown work held and choose this later time.", owner_message_id="fictional-unknown-reschedule")
            clock.return_value = (due + timedelta(seconds=1)).isoformat().replace("+00:00", "Z")
            with self.assertRaises(WorkflowRefusal):
                self.schedule_trigger("cannot-resume-unknown")
            pending = next(item for item in self.engine.resolve(self.sid)["data"]["pending"] if item["kind"] == "reconciliation")
            self.engine.resolve(self.sid, pending_id=pending["pending_id"], evidence_ids=[self.outcome(operation, "succeeded", "reconciliation")])
            self.engine.resume(self.sid, reconciliation_evidence_ids=[self.reconciliation()])
            self.schedule_trigger("actual-outcome-current-trigger")
            self.engine.advance_stage(self.sid, evidence_ids=[])
            verification = self.evidence("verification", {"verification_passed": True, "checked_action_ids": ["fictional-action"], "plan_sha256": self.plan_hash})
            self.engine.advance_stage(self.sid, evidence_ids=[verification])
            self.assertEqual(self.state()["status"], "completed")
            for terminal in ("completed", "stopped"):
                if terminal == "stopped":
                    self.sid = self.engine.create_session(scope=self.scope, checkpoints=[])["session_id"]
                    self.engine.setup(self.sid, timing="scheduled")
                    self.engine.stop(self.sid)
                before = self.state()
                with self.assertRaises(WorkflowRefusal):
                    self.engine.configure_schedule(self.sid, schedule={"when_utc": (due + timedelta(minutes=2)).isoformat().replace("+00:00", "Z"), "description": "Cannot reopen a terminal fixture"}, owner_quote="Terminal state stays closed.", owner_message_id="fictional-terminal-schedule")
                with self.assertRaises(WorkflowRefusal):
                    self.schedule_trigger("terminal-replay")
                self.assertEqual(self.state(), before)

